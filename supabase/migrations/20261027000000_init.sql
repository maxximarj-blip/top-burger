  id                  integer generated by default as identity primary key,
  maquina_id          smallint not null references public.maquinas (id),
  forma_pagamento_id  smallint not null references public.formas_pagamento (id),
  taxa_pct            numeric(7, 5) not null check (taxa_pct >= 0 and taxa_pct < 1),
  repasse_dias_uteis  smallint not null default 0 check (repasse_dias_uteis >= 0),
  vigente_desde       date not null default date '2000-01-01',
  unique (maquina_id, forma_pagamento_id, vigente_desde)
