create table public.comandas (
  id                         bigint generated by default as identity primary key,
  data                       date not null,
  numero                     integer not null check (numero > 0),
  codigo_externo             text,               -- nº do pedido na 99 / iFood
  canal_id                   smallint not null references public.canais (id),
  modalidade                 public.modalidade not null,
  entregador_id              smallint references public.entregadores (id),

  valor_comanda              numeric(12, 2) not null check (valor_comanda >= 0),
  taxa_entrega               numeric(12, 2) not null default 0 check (taxa_entrega >= 0),
  desconto                   numeric(12, 2) not null default 0 check (desconto >= 0),
  valor_pago                 numeric(12, 2) not null check (valor_pago >= 0),

  forma_pagamento_id         smallint references public.formas_pagamento (id),
  maquina_id                 smallint references public.maquinas (id),

  -- Calculados pelo banco (não aceitam valor vindo da tela)
  taxa_pct                   numeric(7, 5) not null default 0,
  valor_taxa                 numeric(12, 2) not null default 0,
  valor_liquido              numeric(12, 2) not null default 0,
  data_prevista_recebimento  date,
  -- quanto o canal "comeu" (comissão da plataforma) ou divergência no caixa próprio
  diferenca                  numeric(12, 2) generated always as
                               (valor_comanda + taxa_entrega - desconto - valor_pago) stored,

  status                     public.status_comanda not null default 'recebido',
  observacao                 text,
  conferido                  boolean not null default false,
  conferido_por              uuid references public.perfis (id),
  conferido_em               timestamptz,

  criado_por                 uuid references public.perfis (id) default auth.uid(),
  criado_em                  timestamptz not null default now(),
  atualizado_por             uuid references public.perfis (id),
  atualizado_em              timestamptz,

  unique (data, numero),
  constraint forma_obrigatoria check (status <> 'recebido' or forma_pagamento_id is not null)
);

create index comandas_data_idx on public.comandas (data);
create index comandas_canal_idx on public.comandas (canal_id, data);
create index comandas_receb_idx on public.comandas (data_prevista_recebimento) where maquina_id is not null;
create index comandas_entregador_idx on public.comandas (entregador_id, data);

