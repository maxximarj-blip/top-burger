-- Papel do usuário logado (null se inativo ou sem perfil)
create or replace function public.papel_atual()
returns public.papel
language sql stable security definer set search_path = public
as $$
  select papel from public.perfis where id = auth.uid() and ativo
$$;

create or replace function public.tem_papel(variadic p public.papel[])
returns boolean
language sql stable security definer set search_path = public
as $$
  select coalesce(public.papel_atual() = any (p), false)
$$;

-- Ao criar um usuário no Auth, cria o perfil.
-- O PRIMEIRO usuário do sistema vira admin automaticamente.
create or replace function public.tg_novo_usuario()
returns trigger
language plpgsql security definer set search_path = public
as $$
declare
  v_papel public.papel;
begin
  if not exists (select 1 from public.perfis) then
    v_papel := 'admin';
  else
    v_papel := coalesce((new.raw_user_meta_data ->> 'papel')::public.papel, 'caixa');
  end if;

  insert into public.perfis (id, nome, email, papel)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'nome', ''), split_part(new.email, '@', 1)),
    new.email,
    v_papel
  );
  return new;
end;
$$;

create trigger tg_auth_novo_usuario
after insert on auth.users
for each row execute function public.tg_novo_usuario();

