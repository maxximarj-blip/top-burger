-- Resumo completo do período (substitui a aba "Resumo")
create or replace function public.relatorio_periodo(p_inicio date, p_fim date)
returns jsonb
language plpgsql stable security invoker set search_path = public
as $$
declare
  r jsonb;
begin
  if not public.tem_papel('admin', 'gerente', 'caixa') then
    raise exception 'Sem permissão';
  end if;

  with c as (
    select c.*, ca.nome as canal, ca.marketplace, coalesce(f.nome, 'Sem forma') as forma, m.nome as maquina,
           e.nome as entregador
      from public.comandas c
      join public.canais ca on ca.id = c.canal_id
      left join public.formas_pagamento f on f.id = c.forma_pagamento_id
      left join public.maquinas m on m.id = c.maquina_id
      left join public.entregadores e on e.id = c.entregador_id
     where c.data between p_inicio and p_fim
       and c.status <> 'cancelado'
  )
  select jsonb_build_object(
    'kpis', (
      select jsonb_build_object(
        'comandas', count(*),
        'valor_comanda', coalesce(sum(valor_comanda), 0),
        'valor_pago', coalesce(sum(valor_pago), 0),
        'valor_taxa', coalesce(sum(valor_taxa), 0),
        'valor_liquido', coalesce(sum(valor_liquido), 0),
        'taxa_entrega', coalesce(sum(taxa_entrega), 0),
        'desconto', coalesce(sum(desconto), 0),
        'comandas_desconto', count(*) filter (where desconto > 0),
        'ticket_medio', coalesce(round(avg(valor_pago), 2), 0),
        'pendentes', count(*) filter (where status = 'pendente'),
        'nao_conferidas', count(*) filter (where not conferido),
        'divergencias', count(*) filter (where not marketplace and abs(diferenca) >= 0.01),
        'comissao_plataformas', coalesce(sum(diferenca) filter (where marketplace), 0)
      ) from c
    ),
    'por_dia', coalesce((
      select jsonb_agg(x order by x.data) from (
        select data, count(*) as comandas, sum(valor_pago) as valor_pago, sum(valor_liquido) as valor_liquido
          from c group by data
      ) x), '[]'),
    'por_canal', coalesce((
      select jsonb_agg(x order by x.valor_pago desc) from (
        select canal, count(*) as comandas, sum(valor_comanda) as valor_comanda, sum(valor_pago) as valor_pago,
               sum(valor_liquido) as valor_liquido, sum(diferenca) as diferenca,
               round(avg(valor_pago), 2) as ticket_medio
          from c group by canal
      ) x), '[]'),
    'por_forma', coalesce((
      select jsonb_agg(x order by x.valor_pago desc) from (
        select forma, count(*) as comandas, sum(valor_pago) as valor_pago, sum(valor_liquido) as valor_liquido
          from c group by forma
      ) x), '[]'),
    'canal_forma', coalesce((
      select jsonb_agg(x) from (
        select canal, forma, count(*) as comandas, sum(valor_pago) as valor_pago
          from c group by canal, forma
      ) x), '[]'),
    'por_maquina', coalesce((
      select jsonb_agg(x order by x.maquina, x.forma) from (
        select maquina, forma, count(*) as comandas, sum(valor_pago) as valor_pago,
               sum(valor_taxa) as valor_taxa, sum(valor_liquido) as valor_liquido
          from c where maquina is not null group by maquina, forma
      ) x), '[]'),
    'por_modalidade', coalesce((
      select jsonb_agg(x order by x.comandas desc) from (
        select modalidade, count(*) as comandas, sum(valor_pago) as valor_pago
          from c group by modalidade
      ) x), '[]'),
    'por_dia_semana', coalesce((
      select jsonb_agg(x order by x.dow) from (
        select extract(isodow from data)::int as dow, count(*) as comandas, sum(valor_pago) as valor_pago,
               count(distinct data) as dias
          from c group by 1
      ) x), '[]')
  ) into r;

  return r;
end;
$$;

-- Acerto de entregadores
create or replace function public.relatorio_entregadores(p_inicio date, p_fim date)
returns table (
  entregador_id smallint, entregador text, entregas bigint, taxas_entrega numeric,
  valor_pedidos numeric, ja_pago numeric, saldo numeric
)
language sql stable security invoker set search_path = public
as $$
  with ent as (
    select c.entregador_id, count(*) as entregas, sum(c.taxa_entrega) as taxas_entrega,
           sum(c.valor_pago) as valor_pedidos
      from public.comandas c
     where c.data between p_inicio and p_fim and c.status <> 'cancelado'
       and c.modalidade = 'delivery_proprio' and c.entregador_id is not null
     group by c.entregador_id
  ), pg as (
    select m.entregador_id, sum(m.valor) as ja_pago
      from public.movimentos_caixa m
     where m.data between p_inicio and p_fim and m.tipo = 'pagamento_entregador'
     group by m.entregador_id
  )
  select e.id, e.nome, coalesce(ent.entregas, 0), coalesce(ent.taxas_entrega, 0),
         coalesce(ent.valor_pedidos, 0), coalesce(pg.ja_pago, 0),
         coalesce(ent.taxas_entrega, 0) - coalesce(pg.ja_pago, 0)
    from public.entregadores e
    left join ent on ent.entregador_id = e.id
    left join pg on pg.entregador_id = e.id
   where ent.entregas is not null or pg.ja_pago is not null
   order by 4 desc;
$$;

-- Agenda de recebíveis das maquininhas
create or replace function public.relatorio_recebiveis(p_inicio date, p_fim date)
returns table (
  data_prevista date, maquina text, forma text, comandas bigint,
  valor_bruto numeric, valor_taxa numeric, valor_liquido numeric
)
language sql stable security invoker set search_path = public
as $$
  select c.data_prevista_recebimento, m.nome, f.nome, count(*),
         sum(c.valor_pago), sum(c.valor_taxa), sum(c.valor_liquido)
    from public.comandas c
    join public.maquinas m on m.id = c.maquina_id
    join public.formas_pagamento f on f.id = c.forma_pagamento_id
   where c.data_prevista_recebimento between p_inicio and p_fim
     and c.status <> 'cancelado'
   group by 1, 2, 3
   order by 1, 2, 3;
$$;

-- Resumo de um dia para o fechamento de caixa
create or replace function public.resumo_dia(p_data date)
returns jsonb
language plpgsql stable security invoker set search_path = public
as $$
declare
  v_fundo      numeric := coalesce((select fundo_troco from public.fechamentos where data = p_data), 0);
  v_dinheiro   numeric;
  v_mov        jsonb;
  v_sup        numeric;
  v_saidas     numeric;
begin
  if not public.tem_papel('admin', 'gerente', 'caixa') then
    raise exception 'Sem permissão';
  end if;

  select coalesce(sum(c.valor_pago), 0) into v_dinheiro
    from public.comandas c join public.formas_pagamento f on f.id = c.forma_pagamento_id
   where c.data = p_data and c.status <> 'cancelado' and f.nome = 'Dinheiro';

  select coalesce(sum(valor) filter (where tipo = 'suprimento'), 0),
         coalesce(sum(valor) filter (where tipo <> 'suprimento'), 0)
    into v_sup, v_saidas
    from public.movimentos_caixa where data = p_data;

  return jsonb_build_object(
    'data', p_data,
    'fundo_troco', v_fundo,
    'vendas_dinheiro', v_dinheiro,
    'suprimentos', v_sup,
    'saidas', v_saidas,
    'dinheiro_esperado', v_fundo + v_dinheiro + v_sup - v_saidas,
    'fechamento', (select to_jsonb(f) from public.fechamentos f where f.data = p_data),
    'resumo', public.relatorio_periodo(p_data, p_data)
  );
end;
$$;

-- Salvar fundo de troco (abertura do caixa)
create or replace function public.definir_fundo_troco(p_data date, p_valor numeric)
returns void
language plpgsql security definer set search_path = public
as $$
begin
  if not public.tem_papel('admin', 'gerente', 'caixa') then
    raise exception 'Sem permissão';
  end if;
  if public.dia_fechado(p_data) and not public.tem_papel('admin') then
    raise exception 'Dia já fechado.';
  end if;
  insert into public.fechamentos (data, fundo_troco) values (p_data, coalesce(p_valor, 0))
  on conflict (data) do update set fundo_troco = excluded.fundo_troco;
end;
$$;

-- Fechar o dia: grava contagem, diferença e foto dos totais, e trava edições
create or replace function public.fechar_dia(p_data date, p_dinheiro_contado numeric, p_observacao text default null)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  v_resumo jsonb;
  v_esperado numeric;
begin
  if not public.tem_papel('admin', 'gerente') then
    raise exception 'Só gerente ou admin pode fechar o caixa.';
  end if;
  if public.dia_fechado(p_data) then
    raise exception 'Esse dia já está fechado.';
  end if;
  if exists (select 1 from public.comandas where data = p_data and status = 'pendente') then
    raise exception 'Existem comandas pendentes nesse dia. Resolva antes de fechar.';
  end if;

  v_resumo := public.resumo_dia(p_data);
  v_esperado := (v_resumo ->> 'dinheiro_esperado')::numeric;

  insert into public.fechamentos (data) values (p_data) on conflict (data) do nothing;
  update public.fechamentos
     set dinheiro_contado  = p_dinheiro_contado,
         dinheiro_esperado = v_esperado,
         diferenca_caixa   = p_dinheiro_contado - v_esperado,
         resumo            = v_resumo -> 'resumo',
         observacao        = p_observacao,
         fechado           = true,
         fechado_por       = auth.uid(),
         fechado_em        = now()
   where data = p_data;

  return public.resumo_dia(p_data);
end;
$$;

create or replace function public.reabrir_dia(p_data date, p_motivo text)
returns void
language plpgsql security definer set search_path = public
as $$
begin
  if not public.tem_papel('admin') then
    raise exception 'Só admin pode reabrir um dia.';
  end if;
  if coalesce(trim(p_motivo), '') = '' then
    raise exception 'Informe o motivo da reabertura.';
  end if;
  update public.fechamentos
     set fechado = false, fechado_por = null, fechado_em = null,
         observacao = concat_ws(E'\n', observacao,
                        format('[Reaberto em %s por %s] %s', to_char(now() at time zone 'America/Sao_Paulo', 'DD/MM/YYYY HH24:MI'),
                               (select nome from public.perfis where id = auth.uid()), p_motivo))
   where data = p_data;
end;
$$;

-- Próximo número de comanda do dia
create or replace function public.proximo_numero(p_data date)
returns integer
language sql stable security invoker set search_path = public
as $$
  select coalesce(max(numero), 0) + 1 from public.comandas where data = p_data
$$;

