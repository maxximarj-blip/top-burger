-- Impede que alguém tire o próprio acesso de admin ou se desative
create or replace function public.tg_perfil_regras()
returns trigger
language plpgsql security definer set search_path = public
as $$
begin
  if new.id = auth.uid() and (new.papel <> old.papel or not new.ativo) then
    raise exception 'Você não pode alterar o seu próprio papel nem se desativar.';
  end if;
  new.email := old.email;
  return new;
end;
$$;

create trigger tg_perfis_regras
before update on public.perfis
for each row execute function public.tg_perfil_regras();

