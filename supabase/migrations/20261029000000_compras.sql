-- Atualiza o custo do insumo com o preço da compra mais recente (não cancelada)
create or replace function public.atualizar_custo_insumo(p_insumo integer)
returns void
language sql security definer set search_path = public
as $$
  update public.insumos i
     set custo_unitario = ult.valor_unitario
    from (
      select it.valor_unitario
        from public.compra_itens it
        join public.compras c on c.id = it.compra_id
       where it.insumo_id = p_insumo and c.status <> 'cancelada'
       order by c.data desc, c.id desc, it.id desc
       limit 1
    ) ult
   where i.id = p_insumo
     and i.custo_unitario is distinct from ult.valor_unitario;
$$;

create or replace function public.tg_compra_item_estoque()
returns trigger
language plpgsql security definer set search_path = public
as $$
declare
  v_status public.status_compra;
begin
  -- itens de compra cancelada não mexem no estoque
  if tg_op in ('UPDATE', 'DELETE') and old.insumo_id is not null then
    select status into v_status from public.compras where id = old.compra_id;
    if coalesce(v_status, 'paga') <> 'cancelada' then
      update public.insumos set estoque_atual = estoque_atual - old.quantidade where id = old.insumo_id;
    end if;
  end if;

  if tg_op in ('INSERT', 'UPDATE') and new.insumo_id is not null then
    select status into v_status from public.compras where id = new.compra_id;
    if v_status <> 'cancelada' then
      update public.insumos set estoque_atual = estoque_atual + new.quantidade where id = new.insumo_id;
    end if;
  end if;

  if tg_op in ('UPDATE', 'DELETE') and old.insumo_id is not null then
    perform public.atualizar_custo_insumo(old.insumo_id);
  end if;
  if tg_op in ('INSERT', 'UPDATE') and new.insumo_id is not null then
    perform public.atualizar_custo_insumo(new.insumo_id);
  end if;

  -- total da compra (não mexe na compra que está sendo excluída)
  if coalesce(current_setting('topburguer.excluindo_compra', true), '') = coalesce(new.compra_id, old.compra_id)::text then
    return null;
  end if;
  update public.compras c
     set valor_itens = coalesce((select sum(valor_total) from public.compra_itens where compra_id = c.id), 0)
   where c.id = coalesce(new.compra_id, old.compra_id);

  return null;
end;
$$;

create trigger tg_compra_itens_estoque
after insert or update or delete on public.compra_itens
for each row execute function public.tg_compra_item_estoque();

-- Cancelar / reativar uma compra estorna / devolve o estoque
create or replace function public.tg_compra_status_estoque()
returns trigger
language plpgsql security definer set search_path = public
as $$
declare
  v_sinal int;
  r record;
begin
  if old.status = new.status or (old.status <> 'cancelada' and new.status <> 'cancelada') then
    return null;
  end if;
  v_sinal := case when new.status = 'cancelada' then -1 else 1 end;
  if new.status = 'cancelada' then
    delete from public.movimentos_caixa where compra_id = new.id;
  end if;
  for r in select insumo_id, sum(quantidade) as q from public.compra_itens
            where compra_id = new.id and insumo_id is not null group by insumo_id
  loop
    update public.insumos set estoque_atual = estoque_atual + v_sinal * r.q where id = r.insumo_id;
    perform public.atualizar_custo_insumo(r.insumo_id);
  end loop;
  return null;
end;
$$;

create trigger tg_compras_status_estoque
after update of status on public.compras
for each row execute function public.tg_compra_status_estoque();

-- ---------------------------------------------------------------------
-- Salvar compra + itens numa transação só
-- ---------------------------------------------------------------------
create or replace function public.salvar_compra(p_compra jsonb, p_itens jsonb, p_lancar_caixa boolean default false)
returns bigint
language plpgsql security invoker set search_path = public
as $$
declare
  v_id bigint := nullif(p_compra ->> 'id', '')::bigint;
  v_item jsonb;
  v_ins public.insumos;
  v_total numeric;
  v_forn text;
begin
  if not public.tem_papel('admin', 'gerente') then
    raise exception 'Só gerente ou admin pode lançar compras.';
  end if;
  if jsonb_typeof(p_itens) <> 'array' or jsonb_array_length(p_itens) = 0 then
    raise exception 'Inclua pelo menos um item na compra.';
  end if;

  if v_id is null then
    insert into public.compras (data, fornecedor_id, fornecedor_nome, numero_nota, forma_pagamento, status,
                                vencimento, data_pagamento, frete, desconto, observacao)
    values (
      coalesce((p_compra ->> 'data')::date, current_date),
      nullif(p_compra ->> 'fornecedor_id', '')::integer,
      nullif(trim(p_compra ->> 'fornecedor_nome'), ''),
      nullif(trim(p_compra ->> 'numero_nota'), ''),
      nullif(p_compra ->> 'forma_pagamento', ''),
      coalesce(nullif(p_compra ->> 'status', ''), 'paga')::public.status_compra,
      nullif(p_compra ->> 'vencimento', '')::date,
      nullif(p_compra ->> 'data_pagamento', '')::date,
      coalesce(nullif(p_compra ->> 'frete', '')::numeric, 0),
      coalesce(nullif(p_compra ->> 'desconto', '')::numeric, 0),
      nullif(trim(p_compra ->> 'observacao'), '')
    )
    returning id into v_id;
  else
    update public.compras set
      data            = coalesce((p_compra ->> 'data')::date, data),
      fornecedor_id   = nullif(p_compra ->> 'fornecedor_id', '')::integer,
      fornecedor_nome = nullif(trim(p_compra ->> 'fornecedor_nome'), ''),
      numero_nota     = nullif(trim(p_compra ->> 'numero_nota'), ''),
      forma_pagamento = nullif(p_compra ->> 'forma_pagamento', ''),
      status          = coalesce(nullif(p_compra ->> 'status', ''), 'paga')::public.status_compra,
      vencimento      = nullif(p_compra ->> 'vencimento', '')::date,
      data_pagamento  = nullif(p_compra ->> 'data_pagamento', '')::date,
      frete           = coalesce(nullif(p_compra ->> 'frete', '')::numeric, 0),
      desconto        = coalesce(nullif(p_compra ->> 'desconto', '')::numeric, 0),
      observacao      = nullif(trim(p_compra ->> 'observacao'), '')
    where id = v_id;
    if not found then
      raise exception 'Compra não encontrada.';
    end if;
    delete from public.compra_itens where compra_id = v_id;
  end if;

  for v_item in select * from jsonb_array_elements(p_itens)
  loop
    v_ins := null;
    if nullif(v_item ->> 'insumo_id', '') is not null then
      select * into v_ins from public.insumos where id = (v_item ->> 'insumo_id')::integer;
    end if;
    insert into public.compra_itens (compra_id, insumo_id, descricao, categoria, unidade, quantidade, valor_unitario)
    values (
      v_id,
      v_ins.id,
      coalesce(nullif(trim(v_item ->> 'descricao'), ''), v_ins.nome, 'Item'),
      coalesce(nullif(v_item ->> 'categoria', ''), v_ins.categoria, 'Outros'),
      coalesce(nullif(v_item ->> 'unidade', ''), v_ins.unidade, 'un'),
      (v_item ->> 'quantidade')::numeric,
      (v_item ->> 'valor_unitario')::numeric
    );
  end loop;

  select total, coalesce(f.nome, c.fornecedor_nome) into v_total, v_forn
    from public.compras c left join public.fornecedores f on f.id = c.fornecedor_id
   where c.id = v_id;
  if v_total < 0 then
    raise exception 'O desconto não pode ser maior que o valor da compra.';
  end if;

  -- Compra já ligada a uma despesa do caixa: mantém o valor igual ao total
  update public.movimentos_caixa set valor = v_total where compra_id = v_id and valor <> v_total;

  -- Paga em dinheiro da gaveta: registra a despesa no caixa do dia
  if p_lancar_caixa then
    insert into public.movimentos_caixa (data, tipo, valor, descricao, compra_id)
    values (coalesce((p_compra ->> 'data_pagamento')::date, (p_compra ->> 'data')::date, current_date),
            'despesa', v_total, format('Compra #%s — %s', v_id, v_forn), v_id);
  end if;

  return v_id;
end;
$$;

-- Marcar como paga (contas a pagar)
create or replace function public.pagar_compra(p_id bigint, p_data date default null, p_forma text default null)
returns void
language plpgsql security invoker set search_path = public
as $$
begin
  if not public.tem_papel('admin', 'gerente') then
    raise exception 'Sem permissão';
  end if;
  update public.compras
     set status = 'paga',
         data_pagamento = coalesce(p_data, current_date),
         forma_pagamento = coalesce(nullif(p_forma, ''), forma_pagamento)
   where id = p_id and status = 'a_pagar';
  if not found then
    raise exception 'Compra não encontrada ou já paga.';
  end if;
end;
$$;

-- ---------------------------------------------------------------------
-- Relatório de compras do período
-- ---------------------------------------------------------------------
create or replace function public.relatorio_compras(p_inicio date, p_fim date)
returns jsonb
language plpgsql stable security invoker set search_path = public
as $$
declare
  v_dias int := p_fim - p_inicio + 1;
  r jsonb;
begin
  if not public.tem_papel('admin', 'gerente') then
    raise exception 'Sem permissão';
  end if;

  with c as (
    select c.*, coalesce(f.nome, c.fornecedor_nome) as fornecedor
      from public.compras c left join public.fornecedores f on f.id = c.fornecedor_id
     where c.data between p_inicio and p_fim and c.status <> 'cancelada'
  ), it as (
    select it.*, c.data, c.fornecedor
      from public.compra_itens it join c on c.id = it.compra_id
  ), vendas as (
    select coalesce(sum(valor_pago), 0) as faturamento
      from public.comandas
     where data between p_inicio and p_fim and status <> 'cancelado'
  ), anterior as (
    select coalesce(sum(total), 0) as total
      from public.compras
     where data between p_inicio - v_dias and p_inicio - 1 and status <> 'cancelada'
  )
  select jsonb_build_object(
    'kpis', (
      select jsonb_build_object(
        'total', coalesce(sum(c.total), 0),
        'compras', count(*),
        'fornecedores', count(distinct coalesce(c.fornecedor_id::text, c.fornecedor_nome)),
        'ticket_medio', coalesce(round(avg(c.total), 2), 0),
        'frete', coalesce(sum(c.frete), 0),
        'desconto', coalesce(sum(c.desconto), 0),
        'pago', coalesce(sum(c.total) filter (where c.status = 'paga'), 0),
        'a_pagar', coalesce(sum(c.total) filter (where c.status = 'a_pagar'), 0),
        'vencidas', count(*) filter (where c.status = 'a_pagar' and c.vencimento < current_date),
        'faturamento', (select faturamento from vendas),
        'periodo_anterior', (select total from anterior)
      ) from c
    ),
    'por_categoria', coalesce((
      select jsonb_agg(x order by x.total desc) from (
        select categoria, sum(valor_total) as total, count(distinct compra_id) as compras
          from it group by categoria
      ) x), '[]'),
    'por_fornecedor', coalesce((
      select jsonb_agg(x order by x.total desc) from (
        select fornecedor, count(*) as compras, sum(total) as total,
               sum(total) filter (where status = 'a_pagar') as a_pagar
          from c group by fornecedor
      ) x), '[]'),
    'por_insumo', coalesce((
      select jsonb_agg(x order by x.total desc) from (
        select descricao as insumo, insumo_id, max(unidade) as unidade, max(categoria) as categoria,
               sum(quantidade) as quantidade, sum(valor_total) as total,
               round(sum(valor_total) / nullif(sum(quantidade), 0), 4) as preco_medio,
               min(valor_unitario) as preco_min, max(valor_unitario) as preco_max,
               count(distinct compra_id) as compras
          from it group by descricao, insumo_id
      ) x), '[]'),
    'por_dia', coalesce((
      select jsonb_agg(x order by x.data) from (
        select data, sum(total) as total, count(*) as compras from c group by data
      ) x), '[]'),
    'por_forma', coalesce((
      select jsonb_agg(x order by x.total desc) from (
        select coalesce(forma_pagamento, 'Não informada') as forma, sum(total) as total, count(*) as compras
          from c group by 1
      ) x), '[]')
  ) into r;
  return r;
end;
$$;

