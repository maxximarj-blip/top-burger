-- =====================================================================
--  TOP BURGUER — Migração 3: Compras
--  Compras com itens, entrada automática no estoque, atualização do
--  custo dos insumos, contas a pagar e relatório do período.
--  Rode no SQL Editor do Supabase DEPOIS das migrações anteriores.
-- =====================================================================

create type public.status_compra as enum ('a_pagar', 'paga', 'cancelada');

create table public.compras (
  id               bigint generated by default as identity primary key,
  data             date not null default current_date,      -- data da compra / recebimento
  fornecedor_id    integer references public.fornecedores (id),
  fornecedor_nome  text,                                     -- compra avulsa (mercado, sem cadastro)
  numero_nota      text,
  forma_pagamento  text,
  status           public.status_compra not null default 'paga',
  vencimento       date,
  data_pagamento   date,
  valor_itens      numeric(12, 2) not null default 0,       -- calculado pelos itens
  frete            numeric(12, 2) not null default 0 check (frete >= 0),
  desconto         numeric(12, 2) not null default 0 check (desconto >= 0),
  total            numeric(12, 2) generated always as (valor_itens + frete - desconto) stored,
  observacao       text,
  criado_por       uuid references public.perfis (id) default auth.uid(),
  criado_em        timestamptz not null default now(),
  atualizado_em    timestamptz,
  constraint fornecedor_informado check (fornecedor_id is not null or nullif(trim(fornecedor_nome), '') is not null),
  constraint vencimento_a_pagar check (status <> 'a_pagar' or vencimento is not null)
);
create index compras_data_idx on public.compras (data);
create index compras_fornecedor_idx on public.compras (fornecedor_id, data);
create index compras_vencimento_idx on public.compras (vencimento) where status = 'a_pagar';

create table public.compra_itens (
  id              bigint generated by default as identity primary key,
  compra_id       bigint not null references public.compras (id) on delete cascade,
  insumo_id       integer references public.insumos (id),
  descricao       text not null,
  categoria       text not null default 'Outros',
  unidade         text not null default 'un',
  quantidade      numeric(12, 3) not null check (quantidade > 0),
  valor_unitario  numeric(12, 4) not null check (valor_unitario >= 0),
  valor_total     numeric(12, 2) generated always as (round(quantidade * valor_unitario, 2)) stored
);
-- despesa lançada no caixa por uma compra paga com dinheiro da gaveta
alter table public.movimentos_caixa add column compra_id bigint references public.compras (id) on delete set null;

create index compra_itens_compra_idx on public.compra_itens (compra_id);
create index compra_itens_insumo_idx on public.compra_itens (insumo_id);

-- ---------------------------------------------------------------------
-- Regras do cabeçalho
-- ---------------------------------------------------------------------
create or replace function public.tg_compra_regras()
returns trigger
language plpgsql security definer set search_path = public
as $$
begin
  if tg_op = 'DELETE' then
    -- apaga os itens enquanto a compra ainda existe (para o estoque ser estornado certo)
    perform set_config('topburguer.excluindo_compra', old.id::text, true);
    delete from public.compra_itens where compra_id = old.id;
    perform set_config('topburguer.excluindo_compra', '', true);
    delete from public.movimentos_caixa where compra_id = old.id;
    return old;
  end if;

  if new.fornecedor_id is not null then
    new.fornecedor_nome := null;
  end if;
  if new.status = 'paga' then
    new.data_pagamento := coalesce(new.data_pagamento, new.data);
  else
    new.data_pagamento := null;
  end if;
  if tg_op = 'UPDATE' then
    new.atualizado_em := now();
    new.criado_por := old.criado_por;
    new.criado_em := old.criado_em;
  end if;
  return new;
end;
$$;

create trigger tg_compras_regras
before insert or update or delete on public.compras
for each row execute function public.tg_compra_regras();

