-- mês com DRE gerado fica travado também para repasses
create or replace function public.tg_repasse_travado()
returns trigger
language plpgsql
as $$
begin
  if exists (select 1 from public.dre_mensal
              where empresa_id = coalesce(new.empresa_id, old.empresa_id)
                and mes in (date_trunc('month', coalesce(new.data, old.data))::date, date_trunc('month', coalesce(old.data, new.data))::date)) then
    raise exception 'O DRE deste mês já foi gerado para esta empresa. Desfaça a geração para alterar os repasses.';
  end if;
  return coalesce(new, old);
end;
$$;
drop trigger if exists repasse_travado on public.repasses;
create trigger repasse_travado before insert or update or delete on public.repasses
  for each row execute function public.tg_repasse_travado();

