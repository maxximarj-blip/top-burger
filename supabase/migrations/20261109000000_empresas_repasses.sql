-- Grava as formas da compra: p_pagamentos = [{forma, valor}] ou, se vazio, a forma única com o total.
-- Devolve quanto saiu em dinheiro.
create or replace function public.gravar_formas_compra(p_id bigint, p_forma text, p_pagamentos jsonb)
returns numeric
language plpgsql security invoker set search_path = public
as $$
declare
  v_total numeric;
  v_soma  numeric;
begin
  select total into v_total from public.compras where id = p_id;
  delete from public.compra_pagamentos where compra_id = p_id;
  if p_pagamentos is not null and jsonb_typeof(p_pagamentos) = 'array' and jsonb_array_length(p_pagamentos) > 0 then
    select coalesce(sum((x ->> 'valor')::numeric), 0) into v_soma from jsonb_array_elements(p_pagamentos) x;
    if abs(v_soma - v_total) >= 0.01 then
      raise exception 'A soma das formas de pagamento (R$ %) é diferente do total da compra (R$ %).',
        translate(to_char(v_soma, 'FM999,990.00'), ',.', '.,'), translate(to_char(v_total, 'FM999,990.00'), ',.', '.,');
    end if;
    insert into public.compra_pagamentos (compra_id, forma, valor)
    select p_id, trim(x ->> 'forma'), (x ->> 'valor')::numeric
      from jsonb_array_elements(p_pagamentos) x
     where nullif(trim(x ->> 'forma'), '') is not null and (x ->> 'valor')::numeric > 0;
    if exists (select 1 from jsonb_array_elements(p_pagamentos) x where nullif(trim(x ->> 'forma'), '') is null and (x ->> 'valor')::numeric > 0) then
      raise exception 'Escolha a forma de cada parte do pagamento.';
    end if;
  elsif nullif(trim(p_forma), '') is not null and v_total > 0 then
    insert into public.compra_pagamentos (compra_id, forma, valor) values (p_id, trim(p_forma), v_total);
  end if;
  -- rótulo legível na compra ("Pix + Dinheiro")
  update public.compras
     set forma_pagamento = (select string_agg(forma, ' + ' order by valor desc, id) from public.compra_pagamentos where compra_id = p_id)
   where id = p_id and exists (select 1 from public.compra_pagamentos where compra_id = p_id);
  return coalesce((select sum(valor) from public.compra_pagamentos where compra_id = p_id and forma = 'Dinheiro'), 0);
end;
$$;

-- salvar_compra: + empresa e formas divididas; a despesa no caixa é só a parte em dinheiro
create or replace function public.salvar_compra(p_compra jsonb, p_itens jsonb, p_lancar_caixa boolean default false)
returns bigint
language plpgsql security invoker set search_path = public
as $$
declare
  v_id bigint := nullif(p_compra ->> 'id', '')::bigint;
  v_item jsonb;
  v_ins public.insumos;
  v_total numeric;
  v_forn text;
  v_forn_id integer;
  v_dinheiro numeric;
  v_emp smallint := coalesce(nullif(p_compra ->> 'empresa_id', '')::smallint, public.empresa_padrao());
  v_chave text := nullif(regexp_replace(coalesce(p_compra ->> 'chave_nfe', ''), '\D', '', 'g'), '');
begin
  if not public.tem_papel('admin', 'gerente') then
    raise exception 'Só gerente ou admin pode lançar compras.';
  end if;
  if jsonb_typeof(p_itens) <> 'array' or jsonb_array_length(p_itens) = 0 then
    raise exception 'Inclua pelo menos um item na compra.';
  end if;
  if v_chave is not null and length(v_chave) <> 44 then
    raise exception 'A chave de acesso da nota deve ter 44 números.';
  end if;
  if v_chave is not null and exists (
       select 1 from public.compras
        where chave_nfe = v_chave and status <> 'cancelada' and id is distinct from v_id) then
    raise exception 'Esta nota já foi lançada (compra #%).',
      (select id from public.compras where chave_nfe = v_chave and status <> 'cancelada' limit 1);
  end if;

  if v_id is null then
    insert into public.compras (empresa_id, data, fornecedor_id, fornecedor_nome, numero_nota, forma_pagamento, status,
                                vencimento, data_pagamento, frete, desconto, observacao, chave_nfe, origem)
    values (
      v_emp,
      coalesce((p_compra ->> 'data')::date, current_date),
      nullif(p_compra ->> 'fornecedor_id', '')::integer,
      nullif(trim(p_compra ->> 'fornecedor_nome'), ''),
      nullif(trim(p_compra ->> 'numero_nota'), ''),
      nullif(p_compra ->> 'forma_pagamento', ''),
      coalesce(nullif(p_compra ->> 'status', ''), 'paga')::public.status_compra,
      nullif(p_compra ->> 'vencimento', '')::date,
      nullif(p_compra ->> 'data_pagamento', '')::date,
      coalesce(nullif(p_compra ->> 'frete', '')::numeric, 0),
      coalesce(nullif(p_compra ->> 'desconto', '')::numeric, 0),
      nullif(trim(p_compra ->> 'observacao'), ''),
      v_chave,
      coalesce(nullif(p_compra ->> 'origem', ''), 'manual')
    )
    returning id into v_id;
  else
    update public.compras set
      empresa_id      = v_emp,
      data            = coalesce((p_compra ->> 'data')::date, data),
      fornecedor_id   = nullif(p_compra ->> 'fornecedor_id', '')::integer,
      fornecedor_nome = nullif(trim(p_compra ->> 'fornecedor_nome'), ''),
      numero_nota     = nullif(trim(p_compra ->> 'numero_nota'), ''),
      forma_pagamento = nullif(p_compra ->> 'forma_pagamento', ''),
      status          = coalesce(nullif(p_compra ->> 'status', ''), 'paga')::public.status_compra,
      vencimento      = nullif(p_compra ->> 'vencimento', '')::date,
      data_pagamento  = nullif(p_compra ->> 'data_pagamento', '')::date,
      frete           = coalesce(nullif(p_compra ->> 'frete', '')::numeric, 0),
      desconto        = coalesce(nullif(p_compra ->> 'desconto', '')::numeric, 0),
      observacao      = nullif(trim(p_compra ->> 'observacao'), ''),
      chave_nfe       = coalesce(v_chave, chave_nfe)
    where id = v_id;
    if not found then
      raise exception 'Compra não encontrada.';
    end if;
    delete from public.compra_itens where compra_id = v_id;
  end if;

  select fornecedor_id into v_forn_id from public.compras where id = v_id;

  for v_item in select * from jsonb_array_elements(p_itens)
  loop
    v_ins := null;
    if nullif(v_item ->> 'insumo_id', '') is not null then
      select * into v_ins from public.insumos where id = (v_item ->> 'insumo_id')::integer;
    end if;
    insert into public.compra_itens (compra_id, insumo_id, descricao, categoria, unidade, quantidade, valor_unitario,
                                     codigo_nota, descricao_nota, quantidade_nota, unidade_nota)
    values (
      v_id,
      v_ins.id,
      coalesce(nullif(trim(v_item ->> 'descricao'), ''), v_ins.nome, 'Item'),
      coalesce(nullif(v_item ->> 'categoria', ''), v_ins.categoria, 'Outros'),
      coalesce(nullif(v_item ->> 'unidade', ''), v_ins.unidade, 'un'),
      (v_item ->> 'quantidade')::numeric,
      (v_item ->> 'valor_unitario')::numeric,
      nullif(trim(v_item ->> 'codigo_nota'), ''),
      nullif(trim(v_item ->> 'descricao_nota'), ''),
      nullif(v_item ->> 'quantidade_nota', '')::numeric,
      nullif(trim(v_item ->> 'unidade_nota'), '')
    );

    if v_forn_id is not null and nullif(v_item ->> 'chave_mapa', '') is not null then
      insert into public.nota_mapeamentos (fornecedor_id, chave, descricao_nota, unidade_nota, insumo_id, categoria, fator)
      values (v_forn_id, v_item ->> 'chave_mapa', v_item ->> 'descricao_nota', v_item ->> 'unidade_nota',
              v_ins.id, case when v_ins.id is null then coalesce(nullif(v_item ->> 'categoria', ''), 'Outros') end,
              coalesce(nullif(v_item ->> 'fator', '')::numeric, 1))
      on conflict (fornecedor_id, chave) do update
        set insumo_id = excluded.insumo_id, categoria = excluded.categoria, fator = excluded.fator,
            descricao_nota = excluded.descricao_nota, unidade_nota = excluded.unidade_nota,
            usos = nota_mapeamentos.usos + 1, atualizado_em = now();
    end if;
  end loop;

  select total, coalesce(f.nome, c.fornecedor_nome) into v_total, v_forn
    from public.compras c left join public.fornecedores f on f.id = c.fornecedor_id
   where c.id = v_id;
  if v_total < 0 then
    raise exception 'O desconto não pode ser maior que o valor da compra.';
  end if;

  v_dinheiro := public.gravar_formas_compra(v_id, p_compra ->> 'forma_pagamento', p_compra -> 'pagamentos');

  -- despesa no caixa = só a parte paga em dinheiro
  update public.movimentos_caixa set valor = v_dinheiro, empresa_id = v_emp
   where compra_id = v_id and v_dinheiro > 0 and (valor <> v_dinheiro or empresa_id <> v_emp);
  delete from public.movimentos_caixa where compra_id = v_id and v_dinheiro = 0;

  if p_lancar_caixa and v_dinheiro > 0 and not exists (select 1 from public.movimentos_caixa where compra_id = v_id) then
    insert into public.movimentos_caixa (data, tipo, valor, descricao, compra_id, empresa_id)
    values (coalesce((p_compra ->> 'data_pagamento')::date, (p_compra ->> 'data')::date, current_date),
            'despesa', v_dinheiro, format('Compra #%s — %s', v_id, v_forn), v_id, v_emp);
  end if;

  return v_id;
end;
$$;

-- Pagar conta: pode informar uma forma (vira forma única) ou várias
drop function if exists public.pagar_compra(bigint, date, text);
create or replace function public.pagar_compra(p_id bigint, p_data date default null, p_forma text default null, p_pagamentos jsonb default null)
returns void
language plpgsql security invoker set search_path = public
as $$
begin
  if not public.tem_papel('admin', 'gerente') then
    raise exception 'Sem permissão';
  end if;
  update public.compras
     set status = 'paga',
         data_pagamento = coalesce(p_data, current_date),
         forma_pagamento = coalesce(nullif(p_forma, ''), forma_pagamento)
   where id = p_id and status = 'a_pagar';
  if not found then
    raise exception 'Compra não encontrada ou já paga.';
  end if;
  if p_pagamentos is not null or nullif(p_forma, '') is not null then
    perform public.gravar_formas_compra(p_id, p_forma, p_pagamentos);
  end if;
end;
$$;

-- Relatório de compras: por empresa e formas divididas
drop function if exists public.relatorio_compras(date, date);
create or replace function public.relatorio_compras(p_inicio date, p_fim date, p_empresa smallint default null)
returns jsonb
language plpgsql stable security invoker set search_path = public
as $$
declare
  v_dias int := p_fim - p_inicio + 1;
  r jsonb;
begin
  if not public.tem_papel('admin', 'gerente') then
    raise exception 'Sem permissão';
  end if;

  with c as (
    select c.*, coalesce(f.nome, c.fornecedor_nome) as fornecedor
      from public.compras c left join public.fornecedores f on f.id = c.fornecedor_id
     where c.data between p_inicio and p_fim and c.status <> 'cancelada'
       and (p_empresa is null or c.empresa_id = p_empresa)
  ), it as (
    select it.*, c.data, c.fornecedor
      from public.compra_itens it join c on c.id = it.compra_id
  ), pg as (
    select p.forma, p.valor, p.compra_id from public.compra_pagamentos p join c on c.id = p.compra_id
    union all
    select 'Não informada', c.total, c.id from c
     where not exists (select 1 from public.compra_pagamentos p where p.compra_id = c.id)
  ), vendas as (
    select coalesce((select sum(valor_pago) from public.comandas
                      where data between p_inicio and p_fim and status <> 'cancelado'
                        and (p_empresa is null or empresa_id = p_empresa)), 0)
         + coalesce((select sum(valor) from public.repasses
                      where data between p_inicio and p_fim and (p_empresa is null or empresa_id = p_empresa)), 0) as faturamento
  ), anterior as (
    select coalesce(sum(total), 0) as total
      from public.compras
     where data between p_inicio - v_dias and p_inicio - 1 and status <> 'cancelada'
       and (p_empresa is null or empresa_id = p_empresa)
  )
  select jsonb_build_object(
    'kpis', (
      select jsonb_build_object(
        'total', coalesce(sum(c.total), 0),
        'compras', count(*),
        'fornecedores', count(distinct coalesce(c.fornecedor_id::text, c.fornecedor_nome)),
        'ticket_medio', coalesce(round(avg(c.total), 2), 0),
        'frete', coalesce(sum(c.frete), 0),
        'desconto', coalesce(sum(c.desconto), 0),
        'pago', coalesce(sum(c.total) filter (where c.status = 'paga'), 0),
        'a_pagar', coalesce(sum(c.total) filter (where c.status = 'a_pagar'), 0),
        'vencidas', count(*) filter (where c.status = 'a_pagar' and c.vencimento < current_date),
        'faturamento', (select faturamento from vendas),
        'periodo_anterior', (select total from anterior)
      ) from c
    ),
    'por_categoria', coalesce((
      select jsonb_agg(x order by x.total desc) from (
        select categoria, sum(valor_total) as total, count(distinct compra_id) as compras
          from it group by categoria
      ) x), '[]'),
    'por_fornecedor', coalesce((
      select jsonb_agg(x order by x.total desc) from (
        select fornecedor, count(*) as compras, sum(total) as total,
               sum(total) filter (where status = 'a_pagar') as a_pagar
          from c group by fornecedor
      ) x), '[]'),
    'por_insumo', coalesce((
      select jsonb_agg(x order by x.total desc) from (
        select descricao as insumo, insumo_id, max(unidade) as unidade, max(categoria) as categoria,
               sum(quantidade) as quantidade, sum(valor_total) as total,
               round(sum(valor_total) / nullif(sum(quantidade), 0), 4) as preco_medio,
               min(valor_unitario) as preco_min, max(valor_unitario) as preco_max,
               count(distinct compra_id) as compras
          from it group by descricao, insumo_id
      ) x), '[]'),
    'por_dia', coalesce((
      select jsonb_agg(x order by x.data) from (
        select data, sum(total) as total, count(*) as compras from c group by data
      ) x), '[]'),
    'por_forma', coalesce((
      select jsonb_agg(x order by x.total desc) from (
        select forma, sum(valor) as total, count(distinct compra_id) as compras from pg group by forma
      ) x), '[]'),
    'por_empresa', coalesce((
      select jsonb_agg(x order by x.total desc) from (
        select e.nome as empresa, count(*) as compras, sum(c.total) as total
          from c join public.empresas e on e.id = c.empresa_id group by e.nome
      ) x), '[]')
  ) into r;
  return r;
end;
$$;

