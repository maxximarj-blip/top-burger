-- =====================================================================
--  TOP BURGUER — Migração 5: notas lidas aguardando conferência
--  A nota lida (XML ou foto) fica salva até ser lançada ou descartada,
--  junto com o que já foi ajustado na conferência. Assim nada se perde
--  ao fechar a tela, trocar de página, atualizar ou trocar de aparelho.
--  Rode no SQL Editor do Supabase DEPOIS das migrações anteriores.
-- =====================================================================

create table public.notas_importadas (
  id             bigint generated by default as identity primary key,
  criado_por     uuid references public.perfis (id) default auth.uid(),
  criado_em      timestamptz not null default now(),
  atualizado_em  timestamptz not null default now(),
  arquivo        text,
  origem         text not null check (origem in ('xml', 'foto')),
  chave_nfe      text,
  emitente       text,
  numero         text,
  total          numeric(12, 2),
  nota           jsonb not null,           -- o que foi lido
  rascunho       jsonb,                    -- ajustes feitos na conferência
  previa         text,                     -- miniatura da foto (data URL), apagada ao lançar
  estado         text not null default 'pendente' check (estado in ('pendente', 'lancada', 'descartada')),
  compra_id      bigint references public.compras (id) on delete set null,
  finalizado_por uuid references public.perfis (id),
  finalizado_em  timestamptz
);
create index notas_importadas_pendentes_idx on public.notas_importadas (criado_em) where estado = 'pendente';

alter table public.notas_importadas enable row level security;
create policy notas_importadas_all on public.notas_importadas for all to authenticated
  using (public.tem_papel('admin', 'gerente')) with check (public.tem_papel('admin', 'gerente'));

create trigger tg_audit after insert or update or delete on public.notas_importadas
  for each row execute function public.tg_auditoria();

-- Lança a compra e marca a nota como lançada na mesma transação
-- (evita lançar duas vezes a mesma leitura, inclusive por duas pessoas ao mesmo tempo)
create or replace function public.lancar_nota_importada(
  p_nota_id bigint, p_compra jsonb, p_itens jsonb, p_lancar_caixa boolean default false)
returns bigint
language plpgsql security invoker set search_path = public
as $$
declare
  v_estado text;
  v_compra bigint;
begin
  select estado, compra_id into v_estado, v_compra
    from public.notas_importadas where id = p_nota_id for update;
  if not found then
    raise exception 'Leitura de nota não encontrada.';
  end if;
  if v_estado = 'lancada' then
    raise exception 'Esta nota já foi lançada (compra #%).', v_compra;
  end if;
  if v_estado = 'descartada' then
    raise exception 'Esta leitura foi descartada.';
  end if;

  v_compra := public.salvar_compra(p_compra, p_itens, p_lancar_caixa);

  update public.notas_importadas
     set estado = 'lancada', compra_id = v_compra, previa = null,
         finalizado_por = auth.uid(), finalizado_em = now(), atualizado_em = now()
   where id = p_nota_id;
  return v_compra;
end;
$$;

-- Auditoria: não grava a miniatura (pesada) no histórico
create or replace function public.tg_auditoria()
returns trigger
language plpgsql security definer set search_path = public
as $$
declare
  v_antes  jsonb := case when tg_op <> 'INSERT' then to_jsonb(old) end;
  v_depois jsonb := case when tg_op <> 'DELETE' then to_jsonb(new) end;
  v_id     text  := coalesce(v_depois ->> 'id', v_depois ->> 'data', v_antes ->> 'id', v_antes ->> 'data');
begin
  if coalesce(current_setting('topburguer.importando', true), '') = 'on' then
    return null;
  end if;
  if tg_table_name = 'notas_importadas' then
    -- só registra mudanças de estado (lançada/descartada), não cada rascunho salvo
    if tg_op = 'UPDATE' then
      if old.estado = new.estado then
        return null;
      end if;
    end if;
    v_antes := v_antes - 'previa' - 'nota' - 'rascunho';
    v_depois := v_depois - 'previa' - 'nota' - 'rascunho';
  end if;
  if tg_op = 'UPDATE' and v_antes = v_depois then
    return null;
  end if;
  insert into public.auditoria (tabela, registro_id, acao, antes, depois, usuario_id, usuario)
  values (tg_table_name, v_id, tg_op, v_antes, v_depois, auth.uid(),
          (select nome from public.perfis where id = auth.uid()));
  return null;
end;
$$;

