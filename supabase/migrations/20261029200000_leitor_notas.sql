-- =====================================================================
--  TOP BURGUER — Migração 4: Leitor de notas fiscais
--  - Chave de acesso da NF-e na compra (impede lançar a mesma nota 2x)
--  - Guarda como o item veio escrito na nota
--  - "Memória" por fornecedor: item da nota -> insumo (+ fator de unidade)
--  Rode no SQL Editor do Supabase DEPOIS das migrações anteriores.
-- =====================================================================

alter table public.compras
  add column chave_nfe text,
  add column origem text not null default 'manual' check (origem in ('manual', 'xml', 'foto'));

-- Mesma nota não entra duas vezes (a não ser que a anterior tenha sido cancelada)
create unique index compras_chave_nfe_uk on public.compras (chave_nfe)
  where chave_nfe is not null and status <> 'cancelada';

alter table public.compra_itens
  add column codigo_nota     text,
  add column descricao_nota  text,
  add column quantidade_nota numeric(12, 3),
  add column unidade_nota    text;

-- ---------------------------------------------------------------------
-- Memória de itens por fornecedor
-- ---------------------------------------------------------------------
create table public.nota_mapeamentos (
  id              bigint generated by default as identity primary key,
  fornecedor_id   integer not null references public.fornecedores (id) on delete cascade,
  chave           text not null,              -- código do produto na nota, ou a descrição normalizada
  descricao_nota  text,
  unidade_nota    text,
  insumo_id       integer references public.insumos (id) on delete cascade,  -- null = não é insumo
  categoria       text,                       -- categoria usada quando não é insumo
  fator           numeric(12, 4) not null default 1 check (fator > 0),
  usos            integer not null default 1,
  atualizado_em   timestamptz not null default now(),
  unique (fornecedor_id, chave)
);

alter table public.nota_mapeamentos enable row level security;
create policy nota_mapeamentos_all on public.nota_mapeamentos for all to authenticated
  using (public.tem_papel('admin', 'gerente')) with check (public.tem_papel('admin', 'gerente'));

-- ---------------------------------------------------------------------
-- salvar_compra: agora aceita chave da nota, origem e grava a memória
-- ---------------------------------------------------------------------
create or replace function public.salvar_compra(p_compra jsonb, p_itens jsonb, p_lancar_caixa boolean default false)
returns bigint
language plpgsql security invoker set search_path = public
as $$
declare
  v_id bigint := nullif(p_compra ->> 'id', '')::bigint;
  v_item jsonb;
  v_ins public.insumos;
  v_total numeric;
  v_forn text;
  v_forn_id integer;
  v_chave text := nullif(regexp_replace(coalesce(p_compra ->> 'chave_nfe', ''), '\D', '', 'g'), '');
begin
  if not public.tem_papel('admin', 'gerente') then
    raise exception 'Só gerente ou admin pode lançar compras.';
  end if;
  if jsonb_typeof(p_itens) <> 'array' or jsonb_array_length(p_itens) = 0 then
    raise exception 'Inclua pelo menos um item na compra.';
  end if;
  if v_chave is not null and length(v_chave) <> 44 then
    raise exception 'A chave de acesso da nota deve ter 44 números.';
  end if;
  if v_chave is not null and exists (
       select 1 from public.compras
        where chave_nfe = v_chave and status <> 'cancelada' and id is distinct from v_id) then
    raise exception 'Esta nota já foi lançada (compra #%).',
      (select id from public.compras where chave_nfe = v_chave and status <> 'cancelada' limit 1);
  end if;

  if v_id is null then
    insert into public.compras (data, fornecedor_id, fornecedor_nome, numero_nota, forma_pagamento, status,
                                vencimento, data_pagamento, frete, desconto, observacao, chave_nfe, origem)
    values (
      coalesce((p_compra ->> 'data')::date, current_date),
      nullif(p_compra ->> 'fornecedor_id', '')::integer,
      nullif(trim(p_compra ->> 'fornecedor_nome'), ''),
      nullif(trim(p_compra ->> 'numero_nota'), ''),
      nullif(p_compra ->> 'forma_pagamento', ''),
      coalesce(nullif(p_compra ->> 'status', ''), 'paga')::public.status_compra,
      nullif(p_compra ->> 'vencimento', '')::date,
      nullif(p_compra ->> 'data_pagamento', '')::date,
      coalesce(nullif(p_compra ->> 'frete', '')::numeric, 0),
      coalesce(nullif(p_compra ->> 'desconto', '')::numeric, 0),
      nullif(trim(p_compra ->> 'observacao'), ''),
      v_chave,
      coalesce(nullif(p_compra ->> 'origem', ''), 'manual')
    )
    returning id into v_id;
  else
    update public.compras set
      data            = coalesce((p_compra ->> 'data')::date, data),
      fornecedor_id   = nullif(p_compra ->> 'fornecedor_id', '')::integer,
      fornecedor_nome = nullif(trim(p_compra ->> 'fornecedor_nome'), ''),
      numero_nota     = nullif(trim(p_compra ->> 'numero_nota'), ''),
      forma_pagamento = nullif(p_compra ->> 'forma_pagamento', ''),
      status          = coalesce(nullif(p_compra ->> 'status', ''), 'paga')::public.status_compra,
      vencimento      = nullif(p_compra ->> 'vencimento', '')::date,
      data_pagamento  = nullif(p_compra ->> 'data_pagamento', '')::date,
      frete           = coalesce(nullif(p_compra ->> 'frete', '')::numeric, 0),
      desconto        = coalesce(nullif(p_compra ->> 'desconto', '')::numeric, 0),
      observacao      = nullif(trim(p_compra ->> 'observacao'), ''),
      chave_nfe       = coalesce(v_chave, chave_nfe)
    where id = v_id;
    if not found then
      raise exception 'Compra não encontrada.';
    end if;
    delete from public.compra_itens where compra_id = v_id;
  end if;

  select fornecedor_id into v_forn_id from public.compras where id = v_id;

  for v_item in select * from jsonb_array_elements(p_itens)
  loop
    v_ins := null;
    if nullif(v_item ->> 'insumo_id', '') is not null then
      select * into v_ins from public.insumos where id = (v_item ->> 'insumo_id')::integer;
    end if;
    insert into public.compra_itens (compra_id, insumo_id, descricao, categoria, unidade, quantidade, valor_unitario,
                                     codigo_nota, descricao_nota, quantidade_nota, unidade_nota)
    values (
      v_id,
      v_ins.id,
      coalesce(nullif(trim(v_item ->> 'descricao'), ''), v_ins.nome, 'Item'),
      coalesce(nullif(v_item ->> 'categoria', ''), v_ins.categoria, 'Outros'),
      coalesce(nullif(v_item ->> 'unidade', ''), v_ins.unidade, 'un'),
      (v_item ->> 'quantidade')::numeric,
      (v_item ->> 'valor_unitario')::numeric,
      nullif(trim(v_item ->> 'codigo_nota'), ''),
      nullif(trim(v_item ->> 'descricao_nota'), ''),
      nullif(v_item ->> 'quantidade_nota', '')::numeric,
      nullif(trim(v_item ->> 'unidade_nota'), '')
    );

    -- memória: da próxima vez este item da nota já vem ligado
    if v_forn_id is not null and nullif(v_item ->> 'chave_mapa', '') is not null then
      insert into public.nota_mapeamentos (fornecedor_id, chave, descricao_nota, unidade_nota, insumo_id, categoria, fator)
      values (v_forn_id, v_item ->> 'chave_mapa', v_item ->> 'descricao_nota', v_item ->> 'unidade_nota',
              v_ins.id, case when v_ins.id is null then coalesce(nullif(v_item ->> 'categoria', ''), 'Outros') end,
              coalesce(nullif(v_item ->> 'fator', '')::numeric, 1))
      on conflict (fornecedor_id, chave) do update
        set insumo_id = excluded.insumo_id, categoria = excluded.categoria, fator = excluded.fator,
            descricao_nota = excluded.descricao_nota, unidade_nota = excluded.unidade_nota,
            usos = nota_mapeamentos.usos + 1, atualizado_em = now();
    end if;
  end loop;

  select total, coalesce(f.nome, c.fornecedor_nome) into v_total, v_forn
    from public.compras c left join public.fornecedores f on f.id = c.fornecedor_id
   where c.id = v_id;
  if v_total < 0 then
    raise exception 'O desconto não pode ser maior que o valor da compra.';
  end if;

  update public.movimentos_caixa set valor = v_total where compra_id = v_id and valor <> v_total;

  if p_lancar_caixa then
    insert into public.movimentos_caixa (data, tipo, valor, descricao, compra_id)
    values (coalesce((p_compra ->> 'data_pagamento')::date, (p_compra ->> 'data')::date, current_date),
            'despesa', v_total, format('Compra #%s — %s', v_id, v_forn), v_id);
  end if;

  return v_id;
end;
$$;

revoke execute on all functions in schema public from public, anon;
grant execute on all functions in schema public to authenticated;
revoke execute on function public.tg_novo_usuario() from authenticated;
