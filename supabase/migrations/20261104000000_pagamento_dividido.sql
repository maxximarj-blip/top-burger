-- =====================================================================
-- Pagamento dividido: uma comanda pode ser paga com mais de uma forma
-- (ex.: R$ 30 no Pix + R$ 20 em dinheiro). Cada forma tem seu valor,
-- sua máquina e sua taxa. Comandas antigas viram "1 pagamento".
-- =====================================================================

create table if not exists public.comanda_pagamentos (
  id                         bigint generated by default as identity primary key,
  comanda_id                 bigint not null references public.comandas (id) on delete cascade,
  forma_pagamento_id         smallint not null references public.formas_pagamento (id),
  maquina_id                 smallint references public.maquinas (id),
  valor                      numeric(12, 2) not null check (valor > 0),
  taxa_pct                   numeric(7, 5) not null default 0,
  valor_taxa                 numeric(12, 2) not null default 0,
  valor_liquido              numeric(12, 2) not null default 0,
  data_prevista_recebimento  date
);
create index if not exists comanda_pagamentos_comanda_idx on public.comanda_pagamentos (comanda_id);
create index if not exists comanda_pagamentos_receb_idx on public.comanda_pagamentos (data_prevista_recebimento) where maquina_id is not null;

alter table public.comanda_pagamentos enable row level security;
drop policy if exists comanda_pagamentos_todos on public.comanda_pagamentos;
create policy comanda_pagamentos_todos on public.comanda_pagamentos for all to authenticated
  using (public.tem_papel('admin', 'gerente', 'caixa')) with check (public.tem_papel('admin', 'gerente', 'caixa'));
grant select, insert, update, delete on public.comanda_pagamentos to authenticated;

-- Calcula a taxa de cada forma e aplica as mesmas travas da comanda
create or replace function public.tg_pagamento_regras()
returns trigger
language plpgsql security definer set search_path = public
as $$
declare
  v_c      public.comandas;
  v_forma  public.formas_pagamento;
  v_taxa   public.maquina_taxas;
  v_import boolean := coalesce(current_setting('topburguer.importando', true), '') = 'on';
begin
  select * into v_c from public.comandas where id = coalesce(new.comanda_id, old.comanda_id);
  if not found then   -- comanda sendo excluída (cascata)
    return coalesce(new, old);
  end if;

  if not v_import then
    if not public.tem_papel('admin') and public.dia_fechado(v_c.data) then
      raise exception 'O dia % já foi fechado. Peça a um administrador para reabrir.', to_char(v_c.data, 'DD/MM/YYYY');
    end if;
    if v_c.conferido and not public.tem_papel('admin', 'gerente') then
      raise exception 'Comanda já conferida. Só gerente/admin pode alterar.';
    end if;
  end if;
  if tg_op = 'DELETE' then
    return old;
  end if;

  select * into v_forma from public.formas_pagamento where id = new.forma_pagamento_id;
  if new.maquina_id is not null and not v_forma.aceita_maquina then
    raise exception 'A forma "%" não passa em maquininha.', v_forma.nome;
  end if;

  new.taxa_pct := 0;
  new.valor_taxa := 0;
  new.data_prevista_recebimento := v_c.data;
  if new.maquina_id is not null then
    select * into v_taxa from public.maquina_taxas
     where maquina_id = new.maquina_id and forma_pagamento_id = new.forma_pagamento_id and vigente_desde <= v_c.data
     order by vigente_desde desc limit 1;
    if not found then
      raise exception 'Não há taxa cadastrada para essa máquina + forma (%). Cadastre em Configurações > Máquinas.', v_forma.nome;
    end if;
    new.taxa_pct := v_taxa.taxa_pct;
    new.valor_taxa := round(new.valor * v_taxa.taxa_pct, 2);
    new.data_prevista_recebimento := public.somar_dias_uteis(v_c.data, v_taxa.repasse_dias_uteis);
  elsif v_forma.online then
    new.data_prevista_recebimento := null;
  end if;
  new.valor_liquido := new.valor - new.valor_taxa;
  return new;
end;
$$;
drop trigger if exists pagamento_regras on public.comanda_pagamentos;
create trigger pagamento_regras before insert or update or delete on public.comanda_pagamentos
  for each row execute function public.tg_pagamento_regras();

-- Depois de mexer nos pagamentos, a comanda recalcula taxa/líquido/forma principal
create or replace function public.tg_pagamento_recalcula()
returns trigger
language plpgsql security definer set search_path = public
as $$
begin
  if coalesce(current_setting('topburguer.carga_pagamentos', true), '') = 'on' then
    return null;
  end if;
  update public.comandas set valor_pago = valor_pago where id = coalesce(new.comanda_id, old.comanda_id);
  return null;
end;
$$;
drop trigger if exists pagamento_recalcula on public.comanda_pagamentos;
create trigger pagamento_recalcula after insert or update or delete on public.comanda_pagamentos
  for each row execute function public.tg_pagamento_recalcula();

drop trigger if exists auditoria_comanda_pagamentos on public.comanda_pagamentos;
create trigger auditoria_comanda_pagamentos after insert or update or delete on public.comanda_pagamentos
  for each row execute function public.tg_auditoria();

-- Comanda gravada sem passar pela tela nova (importação, conferência em lote…):
-- mantém um pagamento único igual à forma da comanda
create or replace function public.tg_comanda_pagamento_unico()
returns trigger
language plpgsql security definer set search_path = public
as $$
declare
  n int;
begin
  if coalesce(current_setting('topburguer.pagamentos_manuais', true), '') = 'on' or pg_trigger_depth() > 1 then
    return null;
  end if;
  if tg_op = 'UPDATE' and new.forma_pagamento_id is not distinct from old.forma_pagamento_id
     and new.maquina_id is not distinct from old.maquina_id and new.valor_pago = old.valor_pago and new.data = old.data then
    return null;
  end if;
  select count(*) into n from public.comanda_pagamentos where comanda_id = new.id;
  if n > 1 then
    return null;   -- dividido: só a tela de comanda altera
  end if;
  delete from public.comanda_pagamentos where comanda_id = new.id;
  if new.forma_pagamento_id is not null and new.valor_pago > 0 then
    insert into public.comanda_pagamentos (comanda_id, forma_pagamento_id, maquina_id, valor)
    values (new.id, new.forma_pagamento_id, new.maquina_id, new.valor_pago);
  end if;
  return null;
end;
$$;
drop trigger if exists comanda_pagamento_unico on public.comandas;
create trigger comanda_pagamento_unico after insert or update on public.comandas
  for each row execute function public.tg_comanda_pagamento_unico();

-- Regras da comanda (mesma de antes + soma das formas quando há pagamentos)
create or replace function public.tg_comanda_regras()
returns trigger
language plpgsql security definer set search_path = public
as $$
declare
  v_forma    public.formas_pagamento;
  v_taxa     public.maquina_taxas;
  v_gestor   boolean := public.tem_papel('admin', 'gerente');
  v_admin    boolean := public.tem_papel('admin');
  v_import   boolean := coalesce(current_setting('topburguer.importando', true), '') = 'on';
begin
  -- Dia fechado: só admin mexe
  if not v_admin and not v_import then
    if tg_op in ('UPDATE', 'DELETE') and public.dia_fechado(old.data) then
      raise exception 'O dia % já foi fechado. Peça a um administrador para reabrir.', to_char(old.data, 'DD/MM/YYYY');
    end if;
    if tg_op in ('INSERT', 'UPDATE') and public.dia_fechado(new.data) then
      raise exception 'O dia % já foi fechado. Peça a um administrador para reabrir.', to_char(new.data, 'DD/MM/YYYY');
    end if;
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;

  -- Caixa não confere nem mexe em comanda já conferida
  if not v_gestor and not v_import then
    if tg_op = 'UPDATE' and old.conferido then
      raise exception 'Comanda já conferida. Só gerente/admin pode alterar.';
    end if;
    if new.conferido and (tg_op = 'INSERT' or not old.conferido) then
      raise exception 'Só gerente/admin pode marcar comanda como conferida.';
    end if;
  end if;

  if new.conferido and (tg_op = 'INSERT' or not old.conferido) then
    new.conferido_por := coalesce(new.conferido_por, auth.uid());
    new.conferido_em  := coalesce(new.conferido_em, now());
  elsif not new.conferido then
    new.conferido_por := null;
    new.conferido_em  := null;
  end if;

  -- Entrega própria precisa de entregador (exceto carga histórica)
  if new.modalidade = 'delivery_proprio' and new.entregador_id is null and not v_import
     and (tg_op = 'INSERT' or new.modalidade is distinct from old.modalidade
          or new.entregador_id is distinct from old.entregador_id) then
    raise exception 'Informe o entregador para delivery próprio.';
  end if;
  if new.modalidade <> 'delivery_proprio' then
    new.entregador_id := null;
  end if;

  -- Pagamento dividido: forma/máquina "principal" = maior pagamento; taxas = soma das formas
  if tg_op = 'UPDATE' and exists (select 1 from public.comanda_pagamentos where comanda_id = new.id) then
    select p.forma_pagamento_id, p.maquina_id into new.forma_pagamento_id, new.maquina_id
      from public.comanda_pagamentos p where p.comanda_id = new.id order by p.valor desc, p.id limit 1;
    select coalesce(sum(valor_taxa), 0), max(data_prevista_recebimento)
      into new.valor_taxa, new.data_prevista_recebimento
      from public.comanda_pagamentos where comanda_id = new.id;
    new.taxa_pct := case when new.valor_pago > 0 then round(new.valor_taxa / new.valor_pago, 5) else 0 end;
    new.valor_liquido := case when new.status = 'cancelado' then 0 else new.valor_pago - new.valor_taxa end;
    if tg_op = 'UPDATE' then
      new.atualizado_por := auth.uid();
      new.atualizado_em  := now();
      new.criado_por     := old.criado_por;
      new.criado_em      := old.criado_em;
    end if;
    return new;
  end if;

  -- Forma de pagamento x máquina
  if new.forma_pagamento_id is not null then
    select * into v_forma from public.formas_pagamento where id = new.forma_pagamento_id;
    if new.maquina_id is not null and not v_forma.aceita_maquina then
      raise exception 'A forma "%" não passa em maquininha.', v_forma.nome;
    end if;
  elsif new.maquina_id is not null then
    raise exception 'Informe a forma de pagamento usada na maquininha.';
  end if;

  -- Taxas
  new.taxa_pct := 0;
  new.valor_taxa := 0;
  new.data_prevista_recebimento := new.data;

  if new.maquina_id is not null then
    select * into v_taxa
      from public.maquina_taxas
     where maquina_id = new.maquina_id
       and forma_pagamento_id = new.forma_pagamento_id
       and vigente_desde <= new.data
     order by vigente_desde desc
     limit 1;

    if not found then
      raise exception 'Não há taxa cadastrada para essa máquina + forma (%). Cadastre em Cadastros > Máquinas.',
        coalesce(v_forma.nome, '?');
    end if;

    new.taxa_pct := v_taxa.taxa_pct;
    new.valor_taxa := round(new.valor_pago * v_taxa.taxa_pct, 2);
    new.data_prevista_recebimento := public.somar_dias_uteis(new.data, v_taxa.repasse_dias_uteis);
  elsif v_forma.online then
    new.data_prevista_recebimento := null;  -- repasse controlado pela plataforma
  end if;

  -- Líquido = o que efetivamente entra (pago - taxa da máquina).
  -- O desconto já está embutido no valor pago, por isso NÃO é subtraído de novo.
  new.valor_liquido := case when new.status = 'cancelado' then 0 else new.valor_pago - new.valor_taxa end;

  if tg_op = 'UPDATE' then
    new.atualizado_por := auth.uid();
    new.atualizado_em  := now();
    new.criado_por     := old.criado_por;
    new.criado_em      := old.criado_em;
  end if;

  return new;
end;
$$;

