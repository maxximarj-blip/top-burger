select set_config('topburguer.importando', 'on', true), set_config('topburguer.carga_pagamentos', 'on', true);
alter table public.comanda_pagamentos disable trigger pagamento_regras;
alter table public.comanda_pagamentos disable trigger auditoria_comanda_pagamentos;
insert into public.comanda_pagamentos (comanda_id, forma_pagamento_id, maquina_id, valor, taxa_pct, valor_taxa, valor_liquido, data_prevista_recebimento)
