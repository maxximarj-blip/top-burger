-- ---------------------------------------------------------------------
-- Salvar comanda + formas de pagamento de uma vez (usado pela tela)
-- ---------------------------------------------------------------------
create or replace function public.salvar_comanda(p_comanda jsonb, p_pagamentos jsonb, p_id bigint default null)
returns bigint
language plpgsql security invoker set search_path = public
as $$
declare
  v_id     bigint := p_id;
  v_soma   numeric := 0;
  v_pago   numeric := (p_comanda ->> 'valor_pago')::numeric;
  v_status public.status_comanda := coalesce(p_comanda ->> 'status', 'recebido')::public.status_comanda;
  v_princ  jsonb;
  v_pg     jsonb;
begin
  perform set_config('topburguer.pagamentos_manuais', 'on', true);
  p_pagamentos := coalesce(p_pagamentos, '[]'::jsonb);

  select coalesce(sum((x ->> 'valor')::numeric), 0) into v_soma from jsonb_array_elements(p_pagamentos) x;
  if jsonb_array_length(p_pagamentos) > 0 and abs(v_soma - v_pago) >= 0.01 then
    raise exception 'A soma das formas (R$ %) é diferente do valor pago (R$ %).', translate(to_char(v_soma, 'FM999,990.00'), ',.', '.,'), translate(to_char(v_pago, 'FM999,990.00'), ',.', '.,');
  end if;
  if v_status = 'recebido' and jsonb_array_length(p_pagamentos) = 0 then
    raise exception 'Informe a forma de pagamento.';
  end if;
  select x into v_princ from jsonb_array_elements(p_pagamentos) x order by (x ->> 'valor')::numeric desc limit 1;

  if v_id is null then
    insert into public.comandas (data, turno, numero, codigo_externo, cliente_id, canal_id, modalidade, entregador_id,
      valor_comanda, taxa_entrega, desconto, valor_pago, forma_pagamento_id, maquina_id, status, observacao, conferido)
    values ((p_comanda ->> 'data')::date, p_comanda ->> 'turno', (p_comanda ->> 'numero')::int, p_comanda ->> 'codigo_externo',
      (p_comanda ->> 'cliente_id')::bigint, (p_comanda ->> 'canal_id')::smallint, (p_comanda ->> 'modalidade')::public.modalidade,
      (p_comanda ->> 'entregador_id')::smallint, (p_comanda ->> 'valor_comanda')::numeric, coalesce((p_comanda ->> 'taxa_entrega')::numeric, 0),
      coalesce((p_comanda ->> 'desconto')::numeric, 0), v_pago, (v_princ ->> 'forma_pagamento_id')::smallint,
      (v_princ ->> 'maquina_id')::smallint, v_status, p_comanda ->> 'observacao', coalesce((p_comanda ->> 'conferido')::boolean, false))
    returning id into v_id;
  else
    update public.comandas set
      data = (p_comanda ->> 'data')::date, turno = p_comanda ->> 'turno', numero = (p_comanda ->> 'numero')::int,
      codigo_externo = p_comanda ->> 'codigo_externo', cliente_id = (p_comanda ->> 'cliente_id')::bigint,
      canal_id = (p_comanda ->> 'canal_id')::smallint, modalidade = (p_comanda ->> 'modalidade')::public.modalidade,
      entregador_id = (p_comanda ->> 'entregador_id')::smallint, valor_comanda = (p_comanda ->> 'valor_comanda')::numeric,
      taxa_entrega = coalesce((p_comanda ->> 'taxa_entrega')::numeric, 0), desconto = coalesce((p_comanda ->> 'desconto')::numeric, 0),
      valor_pago = v_pago, forma_pagamento_id = (v_princ ->> 'forma_pagamento_id')::smallint, maquina_id = (v_princ ->> 'maquina_id')::smallint,
      status = v_status, observacao = p_comanda ->> 'observacao', conferido = coalesce((p_comanda ->> 'conferido')::boolean, false)
    where id = v_id;
    if not found then
      raise exception 'Comanda não encontrada.';
    end if;
  end if;

  delete from public.comanda_pagamentos where comanda_id = v_id;
  for v_pg in select * from jsonb_array_elements(p_pagamentos) loop
    insert into public.comanda_pagamentos (comanda_id, forma_pagamento_id, maquina_id, valor)
    values (v_id, (v_pg ->> 'forma_pagamento_id')::smallint, (v_pg ->> 'maquina_id')::smallint, (v_pg ->> 'valor')::numeric);
  end loop;
  -- sem formas (pendente): volta ao cálculo simples da comanda
  if jsonb_array_length(p_pagamentos) = 0 then
    update public.comandas set forma_pagamento_id = null, maquina_id = null where id = v_id;
  end if;
  return v_id;
end;
$$;

-- ---------------------------------------------------------------------
-- Pagamentos por forma num período (base dos relatórios)
-- Comanda sem forma (pendente) aparece como "Sem forma".
-- ---------------------------------------------------------------------
create or replace function public.pagamentos_periodo(p_inicio date, p_fim date)
returns table (
  comanda_id bigint, data date, turno text, canal text, forma text, maquina text,
  valor numeric, valor_taxa numeric, valor_liquido numeric, data_prevista_recebimento date
)
language sql stable security invoker set search_path = public
as $$
  select c.id, c.data, c.turno, ca.nome, f.nome, m.nome, p.valor, p.valor_taxa, p.valor_liquido, p.data_prevista_recebimento
    from public.comandas c
    join public.canais ca on ca.id = c.canal_id
    join public.comanda_pagamentos p on p.comanda_id = c.id
    join public.formas_pagamento f on f.id = p.forma_pagamento_id
    left join public.maquinas m on m.id = p.maquina_id
   where c.data between p_inicio and p_fim and c.status <> 'cancelado'
  union all
  select c.id, c.data, c.turno, ca.nome, 'Sem forma', null, c.valor_pago, c.valor_taxa, c.valor_liquido, c.data_prevista_recebimento
    from public.comandas c
    join public.canais ca on ca.id = c.canal_id
   where c.data between p_inicio and p_fim and c.status <> 'cancelado'
     and not exists (select 1 from public.comanda_pagamentos p where p.comanda_id = c.id)
$$;

-- Relatório do período (por forma / canal × forma / máquina agora contam cada forma do pagamento)
create or replace function public.relatorio_periodo(p_inicio date, p_fim date)
returns jsonb
language plpgsql stable security invoker set search_path = public
as $$
declare
  r jsonb;
begin
  if not public.tem_papel('admin', 'gerente', 'caixa') then
    raise exception 'Sem permissão';
  end if;

  with c as (
    select c.*, ca.nome as canal, ca.marketplace, coalesce(f.nome, 'Sem forma') as forma, m.nome as maquina,
           e.nome as entregador
      from public.comandas c
      join public.canais ca on ca.id = c.canal_id
      left join public.formas_pagamento f on f.id = c.forma_pagamento_id
      left join public.maquinas m on m.id = c.maquina_id
      left join public.entregadores e on e.id = c.entregador_id
     where c.data between p_inicio and p_fim
       and c.status <> 'cancelado'
  ),
  p as (   -- uma linha por forma usada (pagamento dividido entra em cada forma)
    select * from public.pagamentos_periodo(p_inicio, p_fim)
  )
  select jsonb_build_object(
    'kpis', (
      select jsonb_build_object(
        'comandas', count(*),
        'valor_comanda', coalesce(sum(valor_comanda), 0),
        'valor_pago', coalesce(sum(valor_pago), 0),
        'valor_taxa', coalesce(sum(valor_taxa), 0),
        'valor_liquido', coalesce(sum(valor_liquido), 0),
        'taxa_entrega', coalesce(sum(taxa_entrega), 0),
        'desconto', coalesce(sum(desconto), 0),
        'comandas_desconto', count(*) filter (where desconto > 0),
        'ticket_medio', coalesce(round(avg(valor_pago), 2), 0),
        'pendentes', count(*) filter (where status = 'pendente'),
        'nao_conferidas', count(*) filter (where not conferido),
        'divergencias', count(*) filter (where not marketplace and abs(diferenca) >= 0.01),
        'comissao_plataformas', coalesce(sum(diferenca) filter (where marketplace), 0)
      ) from c
    ),
    'por_dia', coalesce((
      select jsonb_agg(x order by x.data) from (
        select data, count(*) as comandas, sum(valor_pago) as valor_pago, sum(valor_liquido) as valor_liquido
          from c group by data
      ) x), '[]'),
    'por_canal', coalesce((
      select jsonb_agg(x order by x.valor_pago desc) from (
        select canal, count(*) as comandas, sum(valor_comanda) as valor_comanda, sum(valor_pago) as valor_pago,
               sum(valor_liquido) as valor_liquido, sum(diferenca) as diferenca,
               round(avg(valor_pago), 2) as ticket_medio
          from c group by canal
      ) x), '[]'),
    'por_forma', coalesce((
      select jsonb_agg(x order by x.valor_pago desc) from (
        select forma, count(distinct comanda_id) as comandas, sum(valor) as valor_pago, sum(valor_liquido) as valor_liquido
          from p group by forma
      ) x), '[]'),
    'canal_forma', coalesce((
      select jsonb_agg(x) from (
        select canal, forma, count(distinct comanda_id) as comandas, sum(valor) as valor_pago
          from p group by canal, forma
      ) x), '[]'),
    'por_maquina', coalesce((
      select jsonb_agg(x order by x.maquina, x.forma) from (
        select maquina, forma, count(distinct comanda_id) as comandas, sum(valor) as valor_pago,
               sum(valor_taxa) as valor_taxa, sum(valor_liquido) as valor_liquido
          from p where maquina is not null group by maquina, forma
      ) x), '[]'),
    'pagamentos_divididos', (select count(*) from (select comanda_id from p group by comanda_id having count(*) > 1) d),
    'por_modalidade', coalesce((
      select jsonb_agg(x order by x.comandas desc) from (
        select modalidade, count(*) as comandas, sum(valor_pago) as valor_pago
          from c group by modalidade
      ) x), '[]'),
    'por_dia_semana', coalesce((
      select jsonb_agg(x order by x.dow) from (
        select extract(isodow from data)::int as dow, count(*) as comandas, sum(valor_pago) as valor_pago,
               count(distinct data) as dias
          from c group by 1
      ) x), '[]')
  ) into r;

  return r;
end;
$$;

-- Agenda de recebíveis por forma de pagamento
create or replace function public.relatorio_recebiveis(p_inicio date, p_fim date)
returns table (
  data_prevista date, maquina text, forma text, comandas bigint,
  valor_bruto numeric, valor_taxa numeric, valor_liquido numeric
)
language sql stable security invoker set search_path = public
as $$
  select p.data_prevista_recebimento, m.nome, f.nome, count(distinct c.id),
         sum(p.valor), sum(p.valor_taxa), sum(p.valor_liquido)
    from public.comanda_pagamentos p
    join public.comandas c on c.id = p.comanda_id
    join public.maquinas m on m.id = p.maquina_id
    join public.formas_pagamento f on f.id = p.forma_pagamento_id
   where p.data_prevista_recebimento between p_inicio and p_fim
     and c.status <> 'cancelado'
   group by 1, 2, 3
   order by 1, 2, 3;
$$;

-- Fechamento: dinheiro da gaveta soma só a parte paga em dinheiro
create or replace function public.resumo_dia(p_data date)
returns jsonb
language plpgsql stable security invoker set search_path = public
as $$
declare
  v_fundo      numeric := coalesce((select fundo_troco from public.fechamentos where data = p_data), 0);
  v_dinheiro   numeric;
  v_sup        numeric;
  v_saidas     numeric;
begin
  if not public.tem_papel('admin', 'gerente', 'caixa') then
    raise exception 'Sem permissão';
  end if;

  select coalesce(sum(valor), 0) into v_dinheiro
    from public.pagamentos_periodo(p_data, p_data) where forma = 'Dinheiro';

  select coalesce(sum(valor) filter (where tipo = 'suprimento'), 0),
         coalesce(sum(valor) filter (where tipo <> 'suprimento'), 0)
    into v_sup, v_saidas
    from public.movimentos_caixa where data = p_data;

  return jsonb_build_object(
    'data', p_data,
    'fundo_troco', v_fundo,
    'vendas_dinheiro', v_dinheiro,
    'suprimentos', v_sup,
    'saidas', v_saidas,
    'dinheiro_esperado', v_fundo + v_dinheiro + v_sup - v_saidas,
    'fechamento', (select to_jsonb(f) from public.fechamentos f where f.data = p_data),
    'resumo', public.relatorio_periodo(p_data, p_data)
  );
end;
$$;

-- Subtotais por turno com as formas divididas
create or replace function public.resumo_turnos(p_inicio date, p_fim date)
returns jsonb
language sql stable security invoker set search_path = public
as $$
  with c as (
    select c.*, coalesce(c.turno, 'sem') as t
      from public.comandas c
     where c.data between p_inicio and p_fim and c.status <> 'cancelado'
  ),
  p as (
    select coalesce(turno, 'sem') as t, comanda_id, forma, valor from public.pagamentos_periodo(p_inicio, p_fim)
  ),
  formas as (
    select t, jsonb_agg(jsonb_build_object('forma', forma, 'comandas', n, 'valor_pago', vp) order by vp desc) as por_forma,
           coalesce(sum(vp) filter (where forma = 'Dinheiro'), 0) as dinheiro
      from (select t, forma, count(distinct comanda_id) n, sum(valor) vp from p group by t, forma) x
     group by t
  )
  select coalesce(jsonb_agg(jsonb_build_object(
           'turno', r.t, 'comandas', r.comandas, 'valor_comanda', r.valor_comanda, 'taxa_entrega', r.taxa_entrega,
           'desconto', r.desconto, 'valor_pago', r.valor_pago, 'valor_taxa', r.valor_taxa, 'valor_liquido', r.valor_liquido,
           'ticket_medio', r.ticket_medio, 'dinheiro', coalesce(f.dinheiro, 0), 'pendentes', r.pendentes,
           'nao_conferidas', r.nao_conferidas, 'por_forma', coalesce(f.por_forma, '[]'::jsonb)
         ) order by array_position(array['manha', 'tarde', 'noite', 'sem'], r.t)), '[]'::jsonb)
    from (
      select t, count(*) comandas, sum(valor_comanda) valor_comanda, sum(taxa_entrega) taxa_entrega,
             sum(desconto) desconto, sum(valor_pago) valor_pago, sum(valor_taxa) valor_taxa,
             sum(valor_liquido) valor_liquido, round(avg(valor_pago), 2) ticket_medio,
             count(*) filter (where status = 'pendente') pendentes,
             count(*) filter (where not conferido) nao_conferidas
        from c group by t
    ) r
    left join formas f on f.t = r.t
$$;

