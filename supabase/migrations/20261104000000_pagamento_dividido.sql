  from public.comandas c
 where c.forma_pagamento_id is not null and c.valor_pago > 0
   and not exists (select 1 from public.comanda_pagamentos p where p.comanda_id = c.id);
alter table public.comanda_pagamentos enable trigger pagamento_regras;
alter table public.comanda_pagamentos enable trigger auditoria_comanda_pagamentos;
