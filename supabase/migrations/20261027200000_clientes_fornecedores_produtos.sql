  atualizado_em   timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- Produtos (cardápio)
-- ---------------------------------------------------------------------
create table public.produtos (
  id         integer generated by default as identity primary key,
  codigo     text unique,
  nome       text not null,
  categoria  text not null default 'Hambúrgueres',
  descricao  text,
  preco      numeric(12, 2) not null default 0 check (preco >= 0),
  custo      numeric(12, 2) not null default 0 check (custo >= 0),   -- custo estimado (CMV)
  ativo      boolean not null default true,
  ordem      smallint not null default 0,
  atualizado_em timestamptz not null default now()
);

create or replace function public.tg_atualizado_em()
returns trigger language plpgsql as $$
begin
  new.atualizado_em := now();
  return new;
end;
$$;
create trigger tg_insumos_atualizado before update on public.insumos for each row execute function public.tg_atualizado_em();
create trigger tg_produtos_atualizado before update on public.produtos for each row execute function public.tg_atualizado_em();

