create table public.clientes (
  id               bigint generated by default as identity primary key,
  nome             text not null,
  telefone         text,
  email            text,
  documento        text,              -- CPF (opcional, para nota)
  endereco         text,
  bairro           text,
  complemento      text,
  data_nascimento  date,
  observacao       text,
  ativo            boolean not null default true,
  criado_em        timestamptz not null default now()
);
create index clientes_nome_idx on public.clientes (lower(nome));
create index clientes_telefone_idx on public.clientes (telefone);

alter table public.comandas add column cliente_id bigint references public.clientes (id);
create index comandas_cliente_idx on public.comandas (cliente_id, data);

-- Resumo de compras por cliente (respeita o RLS de quem consulta)
create view public.clientes_resumo with (security_invoker = true) as
select cl.*,
       count(c.id) filter (where c.status <> 'cancelado')                         as pedidos,
       coalesce(sum(c.valor_pago) filter (where c.status <> 'cancelado'), 0)      as total_gasto,
       max(c.data) filter (where c.status <> 'cancelado')                         as ultima_compra
  from public.clientes cl
  left join public.comandas c on c.cliente_id = cl.id
 group by cl.id;

-- Ajuste: comandas importadas sem entregador podem ser editadas
-- (o entregador só é exigido em lançamento novo ou ao trocar modalidade/entregador)
create or replace function public.tg_comanda_regras()
returns trigger
language plpgsql security definer set search_path = public
as $$
declare
  v_forma    public.formas_pagamento;
  v_taxa     public.maquina_taxas;
  v_gestor   boolean := public.tem_papel('admin', 'gerente');
  v_admin    boolean := public.tem_papel('admin');
  v_import   boolean := coalesce(current_setting('topburguer.importando', true), '') = 'on';
begin
  -- Dia fechado: só admin mexe
  if not v_admin and not v_import then
    if tg_op in ('UPDATE', 'DELETE') and public.dia_fechado(old.data) then
      raise exception 'O dia % já foi fechado. Peça a um administrador para reabrir.', to_char(old.data, 'DD/MM/YYYY');
    end if;
    if tg_op in ('INSERT', 'UPDATE') and public.dia_fechado(new.data) then
      raise exception 'O dia % já foi fechado. Peça a um administrador para reabrir.', to_char(new.data, 'DD/MM/YYYY');
    end if;
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;

  -- Caixa não confere nem mexe em comanda já conferida
  if not v_gestor and not v_import then
    if tg_op = 'UPDATE' and old.conferido then
      raise exception 'Comanda já conferida. Só gerente/admin pode alterar.';
    end if;
    if new.conferido and (tg_op = 'INSERT' or not old.conferido) then
      raise exception 'Só gerente/admin pode marcar comanda como conferida.';
    end if;
  end if;

  if new.conferido and (tg_op = 'INSERT' or not old.conferido) then
    new.conferido_por := coalesce(new.conferido_por, auth.uid());
    new.conferido_em  := coalesce(new.conferido_em, now());
  elsif not new.conferido then
    new.conferido_por := null;
    new.conferido_em  := null;
  end if;

  -- Entrega própria precisa de entregador (exceto carga histórica)
  if new.modalidade = 'delivery_proprio' and new.entregador_id is null and not v_import
     and (tg_op = 'INSERT' or new.modalidade is distinct from old.modalidade
          or new.entregador_id is distinct from old.entregador_id) then
    raise exception 'Informe o entregador para delivery próprio.';
  end if;
  if new.modalidade <> 'delivery_proprio' then
    new.entregador_id := null;
  end if;

  -- Forma de pagamento x máquina
  if new.forma_pagamento_id is not null then
    select * into v_forma from public.formas_pagamento where id = new.forma_pagamento_id;
    if new.maquina_id is not null and not v_forma.aceita_maquina then
      raise exception 'A forma "%" não passa em maquininha.', v_forma.nome;
    end if;
  elsif new.maquina_id is not null then
    raise exception 'Informe a forma de pagamento usada na maquininha.';
  end if;

  -- Taxas
  new.taxa_pct := 0;
  new.valor_taxa := 0;
  new.data_prevista_recebimento := new.data;

  if new.maquina_id is not null then
    select * into v_taxa
      from public.maquina_taxas
     where maquina_id = new.maquina_id
       and forma_pagamento_id = new.forma_pagamento_id
       and vigente_desde <= new.data
     order by vigente_desde desc
     limit 1;

    if not found then
      raise exception 'Não há taxa cadastrada para essa máquina + forma (%). Cadastre em Cadastros > Máquinas.',
        coalesce(v_forma.nome, '?');
    end if;

    new.taxa_pct := v_taxa.taxa_pct;
    new.valor_taxa := round(new.valor_pago * v_taxa.taxa_pct, 2);
    new.data_prevista_recebimento := public.somar_dias_uteis(new.data, v_taxa.repasse_dias_uteis);
  elsif v_forma.online then
    new.data_prevista_recebimento := null;  -- repasse controlado pela plataforma
  end if;

  -- Líquido = o que efetivamente entra (pago - taxa da máquina).
  -- O desconto já está embutido no valor pago, por isso NÃO é subtraído de novo.
  new.valor_liquido := case when new.status = 'cancelado' then 0 else new.valor_pago - new.valor_taxa end;

  if tg_op = 'UPDATE' then
    new.atualizado_por := auth.uid();
    new.atualizado_em  := now();
    new.criado_por     := old.criado_por;
    new.criado_em      := old.criado_em;
  end if;

  return new;
end;
$$;


