-- Clientes: o caixa cadastra e atualiza no balcão; só gestores excluem
create policy clientes_select on public.clientes for select to authenticated
  using (public.tem_papel('admin', 'gerente', 'caixa'));
create policy clientes_insert on public.clientes for insert to authenticated
  with check (public.tem_papel('admin', 'gerente', 'caixa'));
create policy clientes_update on public.clientes for update to authenticated
  using (public.tem_papel('admin', 'gerente', 'caixa')) with check (public.tem_papel('admin', 'gerente', 'caixa'));
create policy clientes_delete on public.clientes for delete to authenticated
  using (public.tem_papel('admin', 'gerente'));

-- Fornecedores, insumos, produtos: todos leem, gestores mantêm
do $$
declare t text;
begin
  foreach t in array array['fornecedores', 'insumos', 'produtos']
  loop
    execute format('create policy %1$s_select on public.%1$I for select to authenticated
                    using (public.tem_papel(''admin'', ''gerente'', ''caixa''))', t);
    execute format('create policy %1$s_write on public.%1$I for all to authenticated
                    using (public.tem_papel(''admin'', ''gerente''))
                    with check (public.tem_papel(''admin'', ''gerente''))', t);
  end loop;
end $$;

grant select on public.clientes_resumo to authenticated;

