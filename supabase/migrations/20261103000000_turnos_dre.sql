-- =====================================================================
-- 1) Turnos (manhã / tarde / noite) nas comandas
--    A numeração recomeça em cada turno: o nº passa a ser único por
--    data + turno. Comandas antigas (importadas da planilha) ficam
--    "sem turno" e continuam valendo.
-- =====================================================================

alter table public.comandas
  add column if not exists turno text check (turno in ('manha', 'tarde', 'noite'));

alter table public.comandas drop constraint if exists comandas_data_numero_key;
drop index if exists public.comandas_data_turno_numero_uk;
create unique index comandas_data_turno_numero_uk on public.comandas (data, (coalesce(turno, '')), numero);
create index if not exists comandas_data_turno_idx on public.comandas (data, turno);

-- Comanda nova precisa de turno (a carga histórica e as antigas sem turno continuam aceitas)
create or replace function public.tg_comanda_turno()
returns trigger
language plpgsql
as $$
begin
  if new.turno is null
     and coalesce(current_setting('topburguer.importando', true), '') <> 'on'
     and (tg_op = 'INSERT' or old.turno is not null) then
    raise exception 'Informe o turno da comanda (manhã, tarde ou noite).';
  end if;
  return new;
end;
$$;
drop trigger if exists comandas_turno on public.comandas;
create trigger comandas_turno before insert or update on public.comandas
  for each row execute function public.tg_comanda_turno();

-- Próximo nº livre no turno
drop function if exists public.proximo_numero(date);
create or replace function public.proximo_numero(p_data date, p_turno text default null)
returns integer
language sql stable security invoker set search_path = public
as $$
  select coalesce(max(numero), 0) + 1
    from public.comandas
   where data = p_data and (p_turno is null or turno = p_turno)
$$;

-- Subtotais por turno de um período (usado no fechamento do dia)
create or replace function public.resumo_turnos(p_inicio date, p_fim date)
returns jsonb
language sql stable security invoker set search_path = public
as $$
  with c as (
    select c.*, coalesce(c.turno, 'sem') as t, coalesce(f.nome, 'Sem forma') as forma
      from public.comandas c
      left join public.formas_pagamento f on f.id = c.forma_pagamento_id
     where c.data between p_inicio and p_fim and c.status <> 'cancelado'
  ),
  formas as (
    select t, jsonb_agg(jsonb_build_object('forma', forma, 'comandas', n, 'valor_pago', vp) order by vp desc) as por_forma
      from (select t, forma, count(*) n, sum(valor_pago) vp from c group by t, forma) x
     group by t
  )
  select coalesce(jsonb_agg(jsonb_build_object(
           'turno', r.t,
           'comandas', r.comandas,
           'valor_comanda', r.valor_comanda,
           'taxa_entrega', r.taxa_entrega,
           'desconto', r.desconto,
           'valor_pago', r.valor_pago,
           'valor_taxa', r.valor_taxa,
           'valor_liquido', r.valor_liquido,
           'ticket_medio', r.ticket_medio,
           'dinheiro', r.dinheiro,
           'pendentes', r.pendentes,
           'nao_conferidas', r.nao_conferidas,
           'por_forma', coalesce(f.por_forma, '[]'::jsonb)
         ) order by array_position(array['manha', 'tarde', 'noite', 'sem'], r.t)), '[]'::jsonb)
    from (
      select t, count(*) comandas, sum(valor_comanda) valor_comanda, sum(taxa_entrega) taxa_entrega,
             sum(desconto) desconto, sum(valor_pago) valor_pago, sum(valor_taxa) valor_taxa,
             sum(valor_liquido) valor_liquido, round(avg(valor_pago), 2) ticket_medio,
             coalesce(sum(valor_pago) filter (where forma = 'Dinheiro'), 0) dinheiro,
             count(*) filter (where status = 'pendente') pendentes,
             count(*) filter (where not conferido) nao_conferidas
        from c group by t
    ) r
    left join formas f on f.t = r.t
$$;

-- =====================================================================
-- 2) DRE mensal
--    dre_mes(mes)   → DRE calculado na hora (provisório) + pendências
--    gerar_dre(mes) → grava o DRE definitivo, só com o mês todo fechado e conciliado
--    dre_lancamentos → despesas que não passam pelo sistema (folha, aluguel, impostos…)
-- =====================================================================

create table if not exists public.dre_lancamentos (
  id         bigint generated by default as identity primary key,
  mes        date not null check (mes = date_trunc('month', mes)::date),
  grupo      text not null check (grupo in ('impostos', 'pessoal', 'ocupacao', 'administrativas', 'financeiras', 'outras')),
  descricao  text not null,
  valor      numeric(12, 2) not null check (valor > 0),
  criado_por uuid references public.perfis (id) default auth.uid(),
  criado_em  timestamptz not null default now()
);
create index if not exists dre_lancamentos_mes_idx on public.dre_lancamentos (mes);

create table if not exists public.dre_mensal (
  mes        date primary key check (mes = date_trunc('month', mes)::date),
  dados      jsonb not null,
  gerado_por uuid references public.perfis (id) default auth.uid(),
  gerado_em  timestamptz not null default now()
);

alter table public.dre_lancamentos enable row level security;
alter table public.dre_mensal enable row level security;
drop policy if exists dre_lancamentos_admin on public.dre_lancamentos;
create policy dre_lancamentos_admin on public.dre_lancamentos for all to authenticated
  using (public.tem_papel('admin')) with check (public.tem_papel('admin'));
drop policy if exists dre_mensal_admin on public.dre_mensal;
create policy dre_mensal_admin on public.dre_mensal for all to authenticated
  using (public.tem_papel('admin')) with check (public.tem_papel('admin'));
grant select, insert, update, delete on public.dre_lancamentos, public.dre_mensal to authenticated;

drop trigger if exists auditoria_dre_lancamentos on public.dre_lancamentos;
create trigger auditoria_dre_lancamentos after insert or update or delete on public.dre_lancamentos
  for each row execute function public.tg_auditoria();
drop trigger if exists auditoria_dre_mensal on public.dre_mensal;
create trigger auditoria_dre_mensal after insert or delete on public.dre_mensal
  for each row execute function public.tg_auditoria();

-- Lançamentos manuais não podem mudar depois do DRE gerado
create or replace function public.tg_dre_lancamento_travado()
returns trigger
language plpgsql
as $$
begin
  if exists (select 1 from public.dre_mensal where mes = coalesce(new.mes, old.mes)) then
    raise exception 'O DRE deste mês já foi gerado. Desfaça a geração para alterar os lançamentos.';
  end if;
  return coalesce(new, old);
end;
$$;
drop trigger if exists dre_lancamento_travado on public.dre_lancamentos;
create trigger dre_lancamento_travado before insert or update or delete on public.dre_lancamentos
  for each row execute function public.tg_dre_lancamento_travado();

-- Categorias de compra que entram como custo da mercadoria
create or replace function public.dre_grupo_compra(p_categoria text)
returns text
language sql immutable
as $$
  select case
    when p_categoria in ('Carnes', 'Pães', 'Queijos e frios', 'Hortifruti', 'Molhos', 'Congelados', 'Mercearia', 'Bebidas') then 'cmv'
    when p_categoria in ('Embalagens', 'Descartáveis') then 'embalagens'
    else 'operacionais'
  end
$$;

create or replace function public.dre_mes(p_mes date)
returns jsonb
language plpgsql stable security definer set search_path = public
as $$
declare
  v_ini date := date_trunc('month', p_mes)::date;
  v_fim date := (date_trunc('month', p_mes) + interval '1 month - 1 day')::date;
  v_hoje date := (now() at time zone 'America/Sao_Paulo')::date;
  r jsonb;
begin
  if not public.tem_papel('admin') then
    raise exception 'Só o administrador vê o DRE.';
  end if;

  with
  c as (
    select c.*, ca.marketplace
      from public.comandas c join public.canais ca on ca.id = c.canal_id
     where c.data between v_ini and v_fim and c.status <> 'cancelado'
  ),
  vendas as (
    select coalesce(sum(valor_comanda), 0) produtos,
           coalesce(sum(taxa_entrega), 0) entregas,
           coalesce(sum(desconto), 0) descontos,
           coalesce(sum(diferenca) filter (where marketplace), 0) comissoes,
           coalesce(sum(diferenca) filter (where not marketplace), 0) diferencas,
           coalesce(sum(valor_pago), 0) recebido,
           coalesce(sum(valor_taxa), 0) taxas,
           coalesce(sum(valor_liquido), 0) liquido,
           count(*) comandas
      from c
  ),
  compras as (
    select public.dre_grupo_compra(i.categoria) grupo, i.categoria, sum(i.valor_total) valor
      from public.compra_itens i join public.compras co on co.id = i.compra_id
     where co.data between v_ini and v_fim and co.status <> 'cancelada'
     group by 1, 2
  ),
  ajustes_compra as (   -- frete e desconto das notas entram no custo da mercadoria
    select coalesce(sum(frete), 0) - coalesce(sum(desconto), 0) valor
      from public.compras where data between v_ini and v_fim and status <> 'cancelada'
  ),
  caixa as (
    select coalesce(sum(valor) filter (where tipo = 'pagamento_entregador'), 0) entregadores,
           coalesce(sum(valor) filter (where tipo = 'despesa' and compra_id is null), 0) despesas_caixa
      from public.movimentos_caixa where data between v_ini and v_fim
  ),
  manuais as (
    select grupo, sum(valor) valor, jsonb_agg(jsonb_build_object('id', id, 'descricao', descricao, 'valor', valor) order by id) itens
      from public.dre_lancamentos where mes = v_ini group by grupo
  ),
  -- pendências
  dias_venda as (
    select distinct data from public.comandas where data between v_ini and v_fim
  ),
  sem_fechamento as (
    select d.data from dias_venda d
      left join public.fechamentos f on f.data = d.data
     where coalesce(f.fechado, false) = false
  ),
  pend as (
    select (select coalesce(jsonb_agg(to_char(data, 'YYYY-MM-DD') order by data), '[]') from sem_fechamento) dias_abertos,
           (select count(*) from public.comandas where data between v_ini and v_fim and status <> 'cancelado' and not conferido) nao_conferidas,
           (select count(*) from public.comandas where data between v_ini and v_fim and status = 'pendente') pendentes,
           (select count(*) from dias_venda) dias_com_venda
  )
  select jsonb_build_object(
    'mes', to_char(v_ini, 'YYYY-MM-DD'),
    'calculado_em', now(),
    'vendas', (select to_jsonb(v) from vendas v),
    'compras', coalesce((select jsonb_agg(jsonb_build_object('grupo', grupo, 'categoria', categoria, 'valor', valor) order by grupo, valor desc) from compras), '[]'),
    'ajuste_compras', (select valor from ajustes_compra),
    'caixa', (select to_jsonb(x) from caixa x),
    'manuais', coalesce((select jsonb_object_agg(grupo, jsonb_build_object('valor', valor, 'itens', itens)) from manuais), '{}'),
    'pendencias', (select jsonb_build_object(
        'mes_em_andamento', v_fim >= v_hoje,
        'dias_abertos', dias_abertos,
        'nao_conferidas', nao_conferidas,
        'pendentes', pendentes,
        'dias_com_venda', dias_com_venda,
        'sem_movimento', dias_com_venda = 0) from pend),
    'gerado', (select jsonb_build_object('gerado_em', d.gerado_em, 'gerado_por', p.nome)
                 from public.dre_mensal d left join public.perfis p on p.id = d.gerado_por where d.mes = v_ini)
  ) into r;
  return r;
end;
$$;

create or replace function public.gerar_dre(p_mes date)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  v_ini date := date_trunc('month', p_mes)::date;
  v jsonb;
  p jsonb;
begin
  if not public.tem_papel('admin') then
    raise exception 'Só o administrador gera o DRE.';
  end if;
  if exists (select 1 from public.dre_mensal where mes = v_ini) then
    raise exception 'O DRE deste mês já foi gerado.';
  end if;
  v := public.dre_mes(v_ini);
  p := v -> 'pendencias';
  if (p ->> 'mes_em_andamento')::boolean then
    raise exception 'O mês ainda não terminou.';
  end if;
  if (p ->> 'sem_movimento')::boolean then
    raise exception 'Não há vendas neste mês.';
  end if;
  if jsonb_array_length(p -> 'dias_abertos') > 0 then
    raise exception 'FALTA FECHAMENTO: % dia(s) sem fechamento de caixa.', jsonb_array_length(p -> 'dias_abertos');
  end if;
  if (p ->> 'nao_conferidas')::int > 0 or (p ->> 'pendentes')::int > 0 then
    raise exception 'FALTA CONCILIAÇÃO: % comanda(s) não conferida(s).', (p ->> 'nao_conferidas')::int;
  end if;
  insert into public.dre_mensal (mes, dados) values (v_ini, v);
  return public.dre_mes(v_ini);
end;
$$;

create or replace function public.desfazer_dre(p_mes date)
returns void
language plpgsql security definer set search_path = public
as $$
begin
  if not public.tem_papel('admin') then
    raise exception 'Só o administrador pode desfazer o DRE.';
  end if;
  delete from public.dre_mensal where mes = date_trunc('month', p_mes)::date;
end;
$$;

revoke execute on function public.dre_mes(date), public.gerar_dre(date), public.desfazer_dre(date),
  public.resumo_turnos(date, date), public.proximo_numero(date, text) from public, anon;
grant execute on function public.dre_mes(date), public.gerar_dre(date), public.desfazer_dre(date),
  public.resumo_turnos(date, date), public.proximo_numero(date, text) to authenticated;
